export interface K2ShowcaseMiddlewareOptions {
  readonly rootDir?: string
}

function sendJson(res: ServerResponse, statusCode: number, body: unknown): void {
  res.statusCode = statusCode
  res.setHeader('Content-Type', 'application/json; charset=utf-8')
  res.setHeader('Cache-Control', 'no-store')
  res.end(`${JSON.stringify(body)}\n`)
}

export function createK2ShowcaseHttpMiddleware(options?: K2ShowcaseMiddlewareOptions) {
  const rootDir = options?.rootDir ?? DEFAULT_REPO_ROOT

  return (req: IncomingMessage, res: ServerResponse, next: () => void): void => {
    if (!req.url) {
      next()
      return
    }
    const qIdx = req.url.indexOf('?')
    const rawPath = qIdx >= 0 ? req.url.slice(0, qIdx) : req.url
    const queryStr = qIdx >= 0 ? req.url.slice(qIdx + 1) : ''
    const normPath = rawPath.startsWith('/diablo2/') ? rawPath.slice('/diablo2'.length) : rawPath

    if (!normPath.startsWith('/api/k2-showcase/')) {
      next()
      return
    }
    if (req.method !== 'GET') {
      sendJson(res, 405, { ok: false, error: 'Method Not Allowed' })
      return
    }
    const params = new URLSearchParams(queryStr)
    const subRoute = normPath.slice('/api/k2-showcase/'.length)
    try {
      if (subRoute === 'overview') {
        sendJson(res, 200, getK2ShowcaseOverview(rootDir))
        return
      }
      if (subRoute === 'replay') {
        sendJson(res, 200, getK2ReplayShowcaseData(params.get('scenario')?.trim() || K2_SHOWCASE_SCENARIOS[0]))
        return
      }
      if (subRoute === 'gap') {
        sendJson(res, 200, getK2GapShowcaseData(rootDir))
        return
      }
      if (subRoute === 'callgraph') {
        sendJson(res, 200, getK2CallgraphShowcaseData(rootDir))
        return
      }
      if (subRoute === 'fn') {
        const va = params.get('va')?.trim()
        if (!va) {
          sendJson(res, 400, { ok: false, error: 'Missing required query parameter: va' })
          return
        }
        sendJson(res, 200, getK2FunctionDetail(va, rootDir))
        return
      }
      if (subRoute === 'combat') {
        sendJson(res, 200, getK2CombatShowcaseData(rootDir))
        return
      }
      sendJson(res, 404, { ok: false, error: `Unknown K2 showcase route: ${normPath}` })
    } catch (err: unknown) {
      sendJson(res, 400, { ok: false, error: err instanceof Error ? err.message : String(err) })
    }
  }
}
