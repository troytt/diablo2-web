export interface K2LiveGapMeasure extends K2GapMeasure {
  readonly computeMs: number
  /** `Module:0xVA` keys of `dll_union` and of `dll_union ∩ ts_union`, for the call-graph overlay. */
  readonly dllUnionVas: readonly string[]
  readonly tsUnionVas: readonly string[]
}

export interface K2GapResponse {
  readonly ok: true
  readonly historyPath: string
  readonly history: K2GapHistoryFile | null
  readonly historyError: string | null
  readonly live: K2LiveGapMeasure
  readonly liveHeadSha: string | null
  readonly liveMatchesHistoryHead: boolean
  readonly totalScenarioFrames: number
}

let liveGapCache: K2LiveGapMeasure | null = null

/** Runs the 5 replays of the CURRENT tree and measures `|dll_union − ts_union|` for `D2Game`. */
export function measureLiveGap(): K2LiveGapMeasure {
  if (liveGapCache) return liveGapCache
  const t0 = performance.now()
  const dllUnion = new Set<string>()
  const tsUnion = new Set<string>()
  const scenarioGapUnion = new Set<string>()
  const scenarios: K2GapScenarioMeasure[] = []
  let framesReplayed = 0
  let allZero = true
  for (const name of K2_SHOWCASE_SCENARIOS) {
    try {
      const cov = loadCoverage113c(name)
      const dll = new Set<string>()
      for (const h of cov.hits) if (h.module === 'D2Game') dll.add(manifestKey113c(h.module, h.va))
      const res = runReplay113c(name)
      const ts = new Set<string>(res.tsExecutedVas.filter((k) => k.startsWith('D2Game:')))
      let gap = 0
      for (const k of dll) {
        dllUnion.add(k)
        if (!ts.has(k)) {
          gap++
          scenarioGapUnion.add(k)
        }
      }
      for (const k of ts) tsUnion.add(k)
      const zero =
        res.bootCheck === null && res.firstStrictDivergence === null && res.strictHorizon === res.lastGoldenFrame
      if (!zero) allZero = false
      framesReplayed += res.lastGoldenFrame
      scenarios.push({
        scenario: name,
        error: null,
        dllExecuted: dll.size,
        tsExecutedInDll: dll.size - gap,
        gap,
        strictHorizon: res.strictHorizon,
        lastGoldenFrame: res.lastGoldenFrame,
        zeroDivergence: zero,
      })
    } catch (e) {
      allZero = false
      scenarios.push({
        scenario: name,
        error: e instanceof Error ? e.message.slice(0, 240) : String(e),
        dllExecuted: 0,
        tsExecutedInDll: 0,
        gap: 0,
        strictHorizon: 0,
        lastGoldenFrame: 0,
        zeroDivergence: false,
      })
    }
  }
  const unionGapVas = [...dllUnion].filter((k) => !tsUnion.has(k)).sort()
  liveGapCache = {
    scenarios,
    dllUnion: dllUnion.size,
    tsUnionInDll: dllUnion.size - unionGapVas.length,
    unionGap: unionGapVas.length,
    unionOfScenarioGaps: scenarioGapUnion.size,
    unionGapVas,
    framesReplayed,
    allZeroDivergence: allZero,
    computeMs: Math.round(performance.now() - t0),
    dllUnionVas: [...dllUnion].sort(),
    tsUnionVas: [...dllUnion].filter((k) => tsUnion.has(k)).sort(),
  }
  return liveGapCache
}

export const K2_GAP_HISTORY_REL_PATH = 'showcase/k2/data/gap-history.json'

function readHeadSha(rootDir: string): string | null {
  try {
    return execFileSync('git', ['-C', rootDir, 'rev-parse', 'HEAD'], {
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore'],
    }).trim()
  } catch {
    return null
  }
}

export function getK2GapShowcaseData(rootDir: string = DEFAULT_REPO_ROOT): K2GapResponse {
  let history: K2GapHistoryFile | null = null
  let historyError: string | null = null
  const path = resolve(rootDir, K2_GAP_HISTORY_REL_PATH)
  if (!existsSync(path)) {
    historyError = `${K2_GAP_HISTORY_REL_PATH} not generated (run: npx tsx tools/oracle/k2-showcase-gen.ts)`
  } else {
    try {
      const parsed = JSON.parse(readFileSync(path, 'utf8')) as K2GapHistoryFile
      if (parsed.schema !== K2_GAP_HISTORY_SCHEMA) throw new Error(`unexpected schema '${String(parsed.schema)}'`)
      history = parsed
    } catch (e) {
      historyError = e instanceof Error ? e.message : String(e)
    }
  }
  const live = measureLiveGap()
  const liveHeadSha = readHeadSha(rootDir)
  let totalScenarioFrames = 0
  for (const name of K2_SHOWCASE_SCENARIOS) totalScenarioFrames += loadScenario113c(name).frames
  return {
    ok: true,
    historyPath: K2_GAP_HISTORY_REL_PATH,
    history,
    historyError,
    live,
    liveHeadSha,
    liveMatchesHistoryHead: history !== null && liveHeadSha !== null && history.headSha === liveHeadSha,
    totalScenarioFrames,
  }
}

