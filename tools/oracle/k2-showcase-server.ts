export const K2_COMBAT_VECTOR_REL_PATH = 'tests/fixtures/oracle/formulas/dmg.ndjson'
export const K2_COMBAT_DLL_VA = '0x6FCFC0B0'

/** Expected original-DLL outputs of one settlement; `null` = that field was not sampled for this input. */
export interface K2CombatExpected {
  readonly phys: number | null
  readonly elem: number | null
  readonly total: number | null
  readonly absorb: number | null
}

