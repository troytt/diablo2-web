/**
 * [K2] Interactive Visual Showcase backend (`tools/oracle/k2-showcase-server.ts`).
 *
 * Connect-style middleware serving the 4 K2 exhibition zones under `/api/k2-showcase/*`.
 * Every figure is computed from repo files or live kernel replays at request time; nothing is
 * hard-coded, so the page stays correct while the `D2Game` runtime gap is still being closed.
 *
 *   1. `/api/k2-showcase/replay?scenario=`  — frame-by-frame lockstep replay of the 5 K1/K2 scenarios
 *      (golden 1.13c trace vs live `src/d2kern-113c`), with per-frame per-channel divergence status.
 *   2. `/api/k2-showcase/gap`               — measured gap history (`showcase/k2/data/gap-history.json`,
 *      generated by `tools/oracle/k2-showcase-gen.ts`) + a live measurement of the current tree.
 *   3. `/api/k2-showcase/callgraph`, `/fn`  — `manifest-113c.json` `D2Game` functions with honest
 *      `diff-verified` / `ported` totals and per-function evidence.
 *   4. `/api/k2-showcase/combat`            — original-DLL `0x6FCFC0B0` damage-pipeline vectors
 *      (`tests/fixtures/oracle/formulas/dmg.ndjson`) for the in-browser `SUNITDMG_*` sandbox.
 */

