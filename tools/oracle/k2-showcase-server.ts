export const K2_MANIFEST_REL_PATH = 'tools/oracle/callgraph/manifest-113c.json'

interface ManifestCache {
  readonly version: string
  readonly generatedAt: string
  readonly byKey: ReadonlyMap<string, RawManifestFunction>
  readonly list: readonly RawManifestFunction[]
}
const manifestCacheByRoot = new Map<string, ManifestCache>()

function canonVa(va: string): string {
  const n = Number.parseInt(va.toLowerCase().startsWith('0x') ? va.slice(2) : va, 16)
  return `0x${(n >>> 0).toString(16).toUpperCase().padStart(8, '0')}`
}

/** Manifest edge keys are `Module:6FC4E050` (no `0x`); normalises to `Module:0x6FC4E050`. */
function canonEdgeKey(edge: string): string {
  const idx = edge.indexOf(':')
  if (idx < 0) return edge
  return `${edge.slice(0, idx)}:${canonVa(edge.slice(idx + 1))}`
}

function loadManifest(rootDir: string): ManifestCache {
  const hit = manifestCacheByRoot.get(rootDir)
  if (hit) return hit
  const raw = JSON.parse(readFileSync(resolve(rootDir, K2_MANIFEST_REL_PATH), 'utf8')) as {
    version?: string
    generatedAt?: string
    functions: RawManifestFunction[]
  }
  const byKey = new Map<string, RawManifestFunction>()
  for (const fn of raw.functions) byKey.set(`${fn.module}:${canonVa(fn.va)}`, fn)
  const cache: ManifestCache = {
    version: raw.version ?? '',
    generatedAt: raw.generatedAt ?? '',
    byKey,
    list: raw.functions,
  }
  manifestCacheByRoot.set(rootDir, cache)
  return cache
}

export function tallyModules(list: readonly { module: string; status: string }[]): K2ModuleTotals[] {
  const map = new Map<string, { total: number; diffVerified: number; ported: number; unported: number }>()
  for (const fn of list) {
    let t = map.get(fn.module)
    if (!t) {
      t = { total: 0, diffVerified: 0, ported: 0, unported: 0 }
      map.set(fn.module, t)
    }
    t.total++
    if (fn.status === 'diff-verified') t.diffVerified++
    else if (fn.status === 'ported') t.ported++
    else t.unported++
  }
  return [...map.entries()].map(([module, t]) => ({ module, ...t })).sort((a, b) => a.module.localeCompare(b.module))
}

function execCode(key: string, live: K2LiveGapMeasure, dllSet: Set<string>, tsSet: Set<string>): K2ReplayExecCode {
  void live
  if (!dllSet.has(key)) return 0
  return tsSet.has(key) ? 1 : 2
}

export function getK2CallgraphShowcaseData(rootDir: string = DEFAULT_REPO_ROOT): K2CallgraphResponse {
  const manifest = loadManifest(rootDir)
  const live = measureLiveGap()
  const dllSet = new Set(live.dllUnionVas)
  const tsSet = new Set(live.tsUnionVas)
  const kernFiles: string[] = []
  const kernIdx = new Map<string, number>()
  const closure: Record<string, number> = {}
  const functions: K2CallgraphNode[] = []
  for (const fn of manifest.list) {
    if (fn.module !== 'D2Game') continue
    const va = canonVa(fn.va)
    let kf = -1
    if (fn.kernFile) {
      const known = kernIdx.get(fn.kernFile)
      if (known !== undefined) kf = known
      else {
        kf = kernFiles.length
        kernFiles.push(fn.kernFile)
        kernIdx.set(fn.kernFile, kf)
      }
    }
    const exec = execCode(`D2Game:${va}`, live, dllSet, tsSet)
    if (exec !== 0) closure[fn.status] = (closure[fn.status] ?? 0) + 1
    functions.push({
      va,
      name: fn.name,
      status: fn.status,
      size: fn.size,
      topoLevel: fn.topoLevel ?? 0,
      tsSymbol: fn.tsSymbol ?? null,
      kf,
      exec,
    })
  }
  functions.sort((a, b) => (a.va < b.va ? -1 : a.va > b.va ? 1 : 0))
  return {
    ok: true,
    manifestPath: K2_MANIFEST_REL_PATH,
    manifestVersion: manifest.version,
    manifestGeneratedAt: manifest.generatedAt,
    totals: tallyModules(manifest.list),
    kernFiles,
    replay: { dllUnion: live.dllUnion, tsUnionInDll: live.tsUnionInDll, unionGap: live.unionGap },
    replayClosureByStatus: closure,
    functions,
  }
}

export function getK2FunctionDetail(vaSpec: string, rootDir: string = DEFAULT_REPO_ROOT): K2FunctionDetailResponse {
  const manifest = loadManifest(rootDir)
  const parsed = Number.parseInt(vaSpec.trim().toLowerCase().replace(/^d2game:/, '').replace(/^0x/, ''), 16)
  if (!Number.isFinite(parsed)) throw new Error(`Invalid VA specifier: '${vaSpec}'`)
  const key = manifestKey113c('D2Game', parsed)
  const fn = manifest.byKey.get(key)
  if (!fn) throw new Error(`Function ${key} not found in ${K2_MANIFEST_REL_PATH}`)
  const live = measureLiveGap()
  const edge = (e: string): { key: string; name: string; status: string } => {
    const k = canonEdgeKey(e)
    const target = manifest.byKey.get(k)
    return { key: k, name: target?.name ?? '(outside manifest)', status: target?.status ?? 'external' }
  }
  return {
    ok: true,
    module: fn.module,
    va: canonVa(fn.va),
    name: fn.name,
    status: fn.status,
    size: fn.size,
    topoLevel: fn.topoLevel ?? 0,
    sccId: fn.sccId ?? 0,
    tsSymbol: fn.tsSymbol ?? null,
    tsReference: fn.tsReference ?? null,
    kernFile: fn.kernFile ?? null,
    diffEvidence: fn.diffEvidence ?? null,
    exec: execCode(key, live, new Set(live.dllUnionVas), new Set(live.tsUnionVas)),
    externalDeps: fn.externalDeps ?? [],
    callers: (fn.callers ?? []).map(edge),
    callees: (fn.callees ?? []).map(edge),
  }
}

