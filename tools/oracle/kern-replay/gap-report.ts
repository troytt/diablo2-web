/**
 * Exact dynamic gap list for a K1 replay scenario:
 *   npx tsx tools/oracle/kern-replay/gap-report.ts [scenario...]
 *
 * Input: tests/fixtures/oracle/k1/replay/<scenario>.coverage.ndjson.gz, the function-entry coverage
 * recorded by the oracle hook (`cover`, tools/oracle/hook/d2oracle.c) on the original 1.13c DLLs:
 * every manifest D2Game/D2Common entry executed on the server frame thread inside a server frame
 * (C2S delivery + GAME_UpdateGameFrame), with the first frame it ran.
 * Output: docs/oracle/k1-replay/gap-<scenario>.md - executed functions whose manifest status is not
 * `ported`/`diff-verified`, split by module, ordered by first-hit frame then VA.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { join } from 'node:path'
import { gunzipSync } from 'node:zlib'
import { collectImportGraph, legacyReachable } from './import-graph.ts'
import { REPO_ROOT_113C, loadManifest113c, manifestKey113c } from './replay-113c.ts'

export interface CoverageHit113c {
  readonly module: string
  readonly va: number
  readonly firstFrame: number
}

export interface Coverage113c {
  readonly from: number
  readonly to: number
  readonly entries: number
  readonly hit: number
  readonly otherThreadHits: number
  readonly hits: readonly CoverageHit113c[]
}

export function coveragePath113c(name: string): string {
  return join(REPO_ROOT_113C, 'tests/fixtures/oracle/k1/replay', `${name}.coverage.ndjson.gz`)
}

export function loadCoverage113c(name: string): Coverage113c {
  const lines = gunzipSync(readFileSync(coveragePath113c(name))).toString('utf8').split('\n').filter((l) => l.trim().length > 0)
  const hdr = JSON.parse(lines[0] as string) as { k: string; from: number; to: number; entries: number; hit: number; otherThreadHits: number }
  if (hdr.k !== 'hdr') throw new Error(`${name}: coverage has no header`)
  const hits = lines.slice(1).map((l) => {
    const o = JSON.parse(l) as { m: string; va: string; f: number }
    return { module: o.m, va: parseInt(o.va, 16), firstFrame: o.f }
  })
  if (hits.length !== hdr.hit) throw new Error(`${name}: coverage header says ${hdr.hit} hits, file has ${hits.length}`)
  return { from: hdr.from, to: hdr.to, entries: hdr.entries, hit: hdr.hit, otherThreadHits: hdr.otherThreadHits, hits }
}

export interface GapRow113c {
  readonly module: string
  readonly va: number
  readonly name: string
  readonly size: number
  readonly status: string
  readonly firstFrame: number
}

export interface GapSummary113c {
  readonly scenario: string
  readonly coverage: Coverage113c
  readonly executed: Record<string, { total: number; done: number; gap: number; gapBytes: number }>
  readonly gaps: readonly GapRow113c[]
  /** Executed ported/diff-verified functions whose kernFile reaches legacy src/common or src/server. */
  readonly impure: readonly (GapRow113c & { readonly kernFile: string })[]
}

const DONE = new Set(['ported', 'diff-verified'])

export function computeGaps113c(name: string): GapSummary113c {
  const coverage = loadCoverage113c(name)
  const manifest = loadManifest113c()
  const executed: GapSummary113c['executed'] = {}
  const gaps: GapRow113c[] = []
  const impure: Array<GapRow113c & { kernFile: string }> = []
  const purity = new Map<string, boolean>()
  const isPure = (kf: string): boolean => {
    let v = purity.get(kf)
    if (v === undefined) {
      v = legacyReachable(collectImportGraph(REPO_ROOT_113C, [kf]), [kf]).length === 0
      purity.set(kf, v)
    }
    return v
  }
  for (const h of coverage.hits) {
    const f = manifest.get(manifestKey113c(h.module, h.va))
    if (f === undefined) throw new Error(`${name}: covered ${manifestKey113c(h.module, h.va)} is not a manifest function`)
    let e = executed[h.module]
    if (e === undefined) {
      e = { total: 0, done: 0, gap: 0, gapBytes: 0 }
      executed[h.module] = e
    }
    e.total++
    if (DONE.has(f.status)) {
      e.done++
      if (typeof f.kernFile === 'string' && !isPure(f.kernFile)) {
        impure.push({ module: h.module, va: h.va, name: f.name, size: f.size, status: f.status, firstFrame: h.firstFrame, kernFile: f.kernFile })
      }
      continue
    }
    e.gap++
    e.gapBytes += f.size
    gaps.push({ module: h.module, va: h.va, name: f.name, size: f.size, status: f.status, firstFrame: h.firstFrame })
  }
  gaps.sort((a, b) => a.firstFrame - b.firstFrame || a.va - b.va)
  impure.sort((a, b) => a.firstFrame - b.firstFrame || a.va - b.va)
  return { scenario: name, coverage, executed, gaps, impure }
}

function hex(va: number): string {
  return `0x${va.toString(16).toUpperCase().padStart(8, '0')}`
}

export function gapMarkdown113c(s: GapSummary113c): string {
  const c = s.coverage
  const lines = [
    `# K1 replay gap list: ${s.scenario}`,
    '',
    'Generated by `npx tsx tools/oracle/kern-replay/gap-report.ts`; do not edit by hand.',
    '',
    `Source: \`tests/fixtures/oracle/k1/replay/${s.scenario}.coverage.ndjson.gz\`: function-entry coverage of the`,
    `original 1.13c D2Game.dll + D2Common.dll under Wine, frames F${c.from}..F${c.to}, one-shot INT3 on all`,
    `${c.entries} manifest entries, armed only inside the server frame (C2S delivery + \`GAME_UpdateGameFrame\`)`,
    `on the frame thread (${c.hit} entries hit, ${c.otherThreadHits} traps on other threads).`,
    'A row is an executed function whose manifest status is neither `ported` nor `diff-verified`.',
    '`first` is the first frame it ran; frames <= 2 are covered by the boot snapshot, but a function',
    'first seen there may also run again later (coverage is one-shot).',
    '',
    '| Module | executed | ported/dv | gap | gap bytes |',
    '|---|---:|---:|---:|---:|',
  ]
  for (const mod of ['D2Common', 'D2Game']) {
    const e = s.executed[mod]
    if (e === undefined) lines.push(`| ${mod} | 0 | 0 | 0 | 0 |`)
    else lines.push(`| ${mod} | ${e.total} | ${e.done} | ${e.gap} | ${e.gapBytes} |`)
  }
  for (const mod of ['D2Common', 'D2Game']) {
    const rows = s.gaps.filter((g) => g.module === mod)
    lines.push('', `## ${mod} (${rows.length})`, '', '| first | VA | size | status | name |', '|---:|---|---:|---|---|')
    for (const g of rows) lines.push(`| F${g.firstFrame} | \`${hex(g.va)}\` | ${g.size} | ${g.status} | ${g.name} |`)
  }
  lines.push(
    '',
    `## Executed ported/diff-verified functions on an impure kernFile (${s.impure.length})`,
    '',
    'Counted as done above, but their kernel module reaches legacy `src/common`/`src/server` code, so the',
    'pure replay path cannot call them until they are re-homed (tests/oracle/k1/replay-purity.test.ts).',
    '',
    '| first | module | VA | size | status | name | kernFile |',
    '|---:|---|---|---:|---|---|---|',
  )
  for (const g of s.impure) lines.push(`| F${g.firstFrame} | ${g.module} | \`${hex(g.va)}\` | ${g.size} | ${g.status} | ${g.name} | \`${g.kernFile}\` |`)
  lines.push('')
  return lines.join('\n')
}

function main(argv: readonly string[]): void {
  const names =
    argv.length > 0
      ? argv
      : ['a1-town-walk', 'a1c-bloodmoor-fallen', 'a1-bloodmoor-melee', 'p52-dot-ticks', 'p52-item-defense']
  const dir = join(REPO_ROOT_113C, 'docs/oracle/k1-replay')
  mkdirSync(dir, { recursive: true })
  for (const n of names) {
    const s = computeGaps113c(n)
    writeFileSync(join(dir, `gap-${n}.md`), gapMarkdown113c(s))
    const summary = Object.entries(s.executed).map(([m, e]) => `${m} ${e.gap}/${e.total} (${e.gapBytes} B)`).join(', ')
    console.log(`${n}: gap ${summary}; impure ported/dv executed ${s.impure.length}`)
  }
}

if (process.argv[1] !== undefined && import.meta.url === new URL(`file://${process.argv[1]}`).href) {
  main(process.argv.slice(2))
}
