/**
 * K1 kernel replay reporting:
 *   npx tsx tools/oracle/kern-replay/report.ts [--write] [--update-horizons] [scenario...]
 *
 * --write            regenerate docs/oracle/k1-replay/<scenario>.divergence.{json,md}
 * --update-horizons  raise tests/fixtures/oracle/k1/replay/horizons.json to the measured horizons.
 *                    Horizons only ever move up: a measured horizon below the committed one is a
 *                    regression and exits non-zero without touching the file.
 */
import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { join } from 'node:path'
import {
  REPO_ROOT_113C,
  goldenPath113c,
  loadGolden113c,
  runReplay113c,
  snapshotPath113c,
  type ReplayResult113c,
} from './replay-113c.ts'

export const REPLAY_SCENARIOS_113C = [
  'a1-town-walk',
  'a1c-bloodmoor-fallen',
  'a1-bloodmoor-melee',
  'p52-dot-ticks',
  'p52-item-defense',
] as const

export interface Horizon113c {
  readonly bootFrame: number
  readonly strict: number
  readonly pos: number
}

export const HORIZONS_PATH_113C = join(REPO_ROOT_113C, 'tests/fixtures/oracle/k1/replay/horizons.json')
export const DIVERGENCE_DIR_113C = join(REPO_ROOT_113C, 'docs/oracle/k1-replay')

export function loadHorizons113c(): Record<string, Horizon113c> {
  return JSON.parse(readFileSync(HORIZONS_PATH_113C, 'utf8')) as Record<string, Horizon113c>
}

function sha256File(path: string): string {
  return createHash('sha256').update(readFileSync(path)).digest('hex')
}

export interface DivergenceArtifact113c {
  readonly scenario: string
  readonly bootFrame: number
  readonly lastGoldenFrame: number
  readonly strictHorizon: number
  readonly posHorizon: number
  readonly matchedKernelFrames: number
  readonly bootCheck: ReplayResult113c['bootCheck']
  readonly firstDivergence: ReplayResult113c['firstStrictDivergence']
  readonly firstPosDivergence: ReplayResult113c['firstPosDivergence']
  readonly unportedHit: ReplayResult113c['unportedHit']
  readonly context: ReadonlyArray<{ readonly frame: number; readonly row: unknown }>
  readonly goldenSha256: string
  readonly snapshotSha256: string
}

export function buildArtifact113c(r: ReplayResult113c): DivergenceArtifact113c {
  const d = r.firstStrictDivergence
  const context: Array<{ frame: number; row: unknown }> = []
  if (d !== null && d.id !== null && d.key.startsWith('t')) {
    const golden = loadGolden113c(r.scenario)
    for (let f = d.frame - 3; f <= d.frame; f++) {
      const rows = golden.frames.get(f)?.[d.key as `t${number}`]
      if (rows === undefined) continue
      context.push({ frame: f, row: rows.find((row) => row[0] === d.id) })
    }
  }
  return {
    scenario: r.scenario,
    bootFrame: r.bootFrame,
    lastGoldenFrame: r.lastGoldenFrame,
    strictHorizon: r.strictHorizon,
    posHorizon: r.posHorizon,
    matchedKernelFrames: Math.max(0, r.strictHorizon - r.bootFrame),
    bootCheck: r.bootCheck,
    firstDivergence: d,
    firstPosDivergence: r.firstPosDivergence,
    unportedHit: r.unportedHit,
    context,
    goldenSha256: sha256File(goldenPath113c(r.scenario)),
    snapshotSha256: sha256File(snapshotPath113c(r.scenario, r.bootFrame)),
  }
}

function artifactMarkdown(a: DivergenceArtifact113c): string {
  const d = a.firstDivergence
  const lines = [
    `# K1 kernel replay: ${a.scenario}`,
    '',
    'Generated by `npx tsx tools/oracle/kern-replay/report.ts --write`; do not edit by hand.',
    '',
    `| | |`,
    `|---|---|`,
    `| Boot snapshot | F${a.bootFrame} (\`${a.snapshotSha256.slice(0, 16)}…\`) |`,
    `| Golden | F1..F${a.lastGoldenFrame} (\`${a.goldenSha256.slice(0, 16)}…\`) |`,
    `| Boot check (hydrated F${a.bootFrame} vs golden, strict) | ${a.bootCheck === null ? 'identical' : `DIFFERS: ${JSON.stringify(a.bootCheck)}`} |`,
    `| Strict horizon (all fields incl. seeds, stats) | F${a.strictHorizon} |`,
    `| Position horizon (id/class/mode/x/y) | F${a.posHorizon} |`,
    `| Kernel frames matched | ${a.matchedKernelFrames} of ${a.lastGoldenFrame - a.bootFrame} |`,
    '',
    '## First divergence',
    '',
  ]
  if (d === null) lines.push('None: the kernel matches the golden on every frame.')
  else {
    lines.push(`- frame: F${d.frame}`, `- key: \`${d.key}\``, `- unit id: ${d.id === null ? '-' : d.id}`, `- field: \`${d.field}\``)
    lines.push(`- expected: \`${JSON.stringify(d.expected)}\``, `- actual: \`${JSON.stringify(d.actual)}\``)
  }
  if (a.unportedHit !== null) {
    lines.push('', '## Unported kernel function hit', '', `- \`${a.unportedHit.key}\` (manifest status \`${a.unportedHit.status}\`) at F${a.unportedHit.frame}`, `- ${a.unportedHit.reason}`)
  }
  if (a.context.length > 0) {
    lines.push('', '## Golden context', '', '| frame | row |', '|---|---|')
    for (const c of a.context) lines.push(`| F${c.frame} | \`${JSON.stringify(c.row)}\` |`)
  }
  lines.push('')
  return lines.join('\n')
}

export function writeArtifact113c(a: DivergenceArtifact113c): void {
  mkdirSync(DIVERGENCE_DIR_113C, { recursive: true })
  writeFileSync(join(DIVERGENCE_DIR_113C, `${a.scenario}.divergence.json`), `${JSON.stringify(a, null, 2)}\n`)
  writeFileSync(join(DIVERGENCE_DIR_113C, `${a.scenario}.divergence.md`), artifactMarkdown(a))
}

/** Upward-only horizon merge; returns the regressions (empty when the update is allowed). */
export function mergeHorizons113c(
  committed: Record<string, Horizon113c>,
  measured: readonly ReplayResult113c[],
): { readonly next: Record<string, Horizon113c>; readonly regressions: string[] } {
  const next: Record<string, Horizon113c> = { ...committed }
  const regressions: string[] = []
  for (const r of measured) {
    const old = committed[r.scenario]
    if (old !== undefined) {
      if (r.strictHorizon < old.strict) regressions.push(`${r.scenario}: strict F${old.strict} -> F${r.strictHorizon}`)
      if (r.posHorizon < old.pos) regressions.push(`${r.scenario}: pos F${old.pos} -> F${r.posHorizon}`)
    }
    next[r.scenario] = {
      bootFrame: r.bootFrame,
      strict: old === undefined ? r.strictHorizon : Math.max(old.strict, r.strictHorizon),
      pos: old === undefined ? r.posHorizon : Math.max(old.pos, r.posHorizon),
    }
  }
  return { next, regressions }
}

function main(argv: readonly string[]): number {
  const write = argv.includes('--write')
  const update = argv.includes('--update-horizons')
  const named = argv.filter((a) => !a.startsWith('--'))
  const scenarios = named.length > 0 ? named : [...REPLAY_SCENARIOS_113C]
  const results = scenarios.map((s) => runReplay113c(s))
  for (const r of results) {
    const a = buildArtifact113c(r)
    console.log(
      `${r.scenario}: boot F${r.bootFrame} ${r.bootCheck === null ? 'ok' : 'MISMATCH'}, strict F${r.strictHorizon}, pos F${r.posHorizon}, first divergence ${JSON.stringify(r.firstStrictDivergence)}`,
    )
    if (write) writeArtifact113c(a)
  }
  if (update) {
    let committed: Record<string, Horizon113c> = {}
    try {
      committed = loadHorizons113c()
    } catch {
      committed = {}
    }
    const { next, regressions } = mergeHorizons113c(committed, results)
    if (regressions.length > 0) {
      console.error(`horizon regression, horizons.json left unchanged:\n  ${regressions.join('\n  ')}`)
      return 1
    }
    writeFileSync(HORIZONS_PATH_113C, `${JSON.stringify(next, null, 2)}\n`)
  }
  return 0
}

if (process.argv[1] !== undefined && import.meta.url === new URL(`file://${process.argv[1]}`).href) {
  process.exitCode = main(process.argv.slice(2))
}
