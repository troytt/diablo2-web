def fix_d2s_checksum(buf: bytearray) -> bytes:
    struct.pack_into('<I', buf, 0x08, len(buf))
    struct.pack_into('<I', buf, 0x0C, 0)
    csum = 0
    for b in buf:
        csum = (((csum << 1) | (csum >> 31)) + b) & 0xFFFFFFFF
    struct.pack_into('<I', buf, 0x0C, csum)
    return bytes(buf)


def make_new_char_d2s(cls_id: int, progression: int = 15, difficulty: int = 0, act: int = 0) -> bytes:
    with open(os.path.join(LEGACY_SAVES_DIR, 'a1-barbarian-l1.d2s'), 'rb') as f:
        raw = bytearray(f.read())
    raw[0x28] = cls_id & 0xFF
    raw[0x25] = progression
    raw[0xA8] = 0
    raw[0xA9] = 0
    raw[0xAA] = 0
    raw[0xA8 + difficulty] = 0x80 | act
    return fix_d2s_checksum(raw)


def make_compact_jm(code4: str, x: int, y: int, flags: int = 0x00A20010, page: int = 1) -> bytes:
    if len(code4) != 4:
        raise ValueError(f'item code must be 4 chars: {code4!r}')
    val = (
        (flags & 0xFFFFFFFF)
        | ((101 & 0x3FF) << 32)
        | ((0 & 0x7) << 42)
        | ((0 & 0xF) << 45)
        | ((x & 0xF) << 49)
        | ((y & 0xF) << 53)
        | ((page & 0x7) << 57)
    )
    for k, ch in enumerate(code4):
        val |= (ord(ch) & 0xFF) << (60 + k * 8)
    return b'JM' + val.to_bytes(12, 'little')


def build_char_save_from_template(
    template_name: str,
    act: int = 0,
    difficulty: int = 0,
    quest_words: dict | None = None,
    extra_compact_items=(),
    unlock_all_waypoints: bool = True,
    skill_overrides: dict[int, int] | None = None,
    progression: int = 15,
) -> bytes:
    with open(os.path.join(LEGACY_SAVES_DIR, template_name), 'rb') as f:
        raw = bytearray(f.read())
    raw[0x25] = progression
    raw[0xA8] = 0
    raw[0xA9] = 0
    raw[0xAA] = 0
    raw[0xA8 + difficulty] = 0x80 | act
    merged = {**ACT_UNLOCK_WORDS[act], **(quest_words or {})}
    woo = raw.find(b'Woo!')
    if woo >= 0:
        for d in range(3):
            base_q = woo + 10 + d * 0x60
            for widx, wval in merged.items():
                struct.pack_into('<H', raw, base_q + widx * 2, wval)
    if unlock_all_waypoints:
        ws = raw.find(b'WS')
        if ws >= 0:
            for d in range(3):
                wp_off = ws + 8 + d * 24 + 2
                raw[wp_off : wp_off + 5] = bytes([0xFF, 0xFF, 0xFF, 0xFF, 0x7F])
    if skill_overrides is not None:
        if_off = raw.find(b'if')
        if if_off >= 0:
            for idx, lvl in skill_overrides.items():
                raw[if_off + 2 + idx] = lvl & 0xFF
    if extra_compact_items:
        jm = raw.find(b'JM')
        if jm < 0:
            raise ValueError('template has no JM section')
        cnt = struct.unpack_from('<H', raw, jm + 2)[0]
        struct.pack_into('<H', raw, jm + 2, cnt + len(extra_compact_items))
        kf = raw.find(b'kf')
        corpse_jm = raw.rfind(b'JM', jm + 4, kf)
        if corpse_jm < 0:
            raise ValueError('could not locate corpse JM')
        raw = raw[:corpse_jm] + b''.join(extra_compact_items) + raw[corpse_jm:]
    return fix_d2s_checksum(raw)


def build_god_sorc_d2s(
    act: int,
    difficulty: int = 0,
    quest_words: dict | None = None,
    extra_compact_items=(),
    strip_staff: bool = True,
    hp: int = 2500,
    mp: int = 1000,
    dead_rogue_merc: bool = False,
) -> bytes:
    raw = bytearray(
        build_char_save_from_template(
            'sorceress-l40-elemental.d2s',
            act=act,
            difficulty=difficulty,
            quest_words=quest_words,
            extra_compact_items=extra_compact_items,
            unlock_all_waypoints=True,
            skill_overrides=SORC_SKILLS,
        )
    )
    gf = raw.find(b'gf')
    if_off = raw.find(b'if', gf)
    nbytes = if_off - (gf + 2)
    val = int.from_bytes(raw[gf + 2 : if_off], 'little')

    def set_bits(v: int, pos: int, width: int, new_val: int) -> int:
        mask = ((1 << width) - 1) << pos
        return (v & ~mask) | ((new_val & ((1 << width) - 1)) << pos)

    val = set_bits(val, 9, 10, 100)            # Str = 100
    val = set_bits(val, 47, 10, 100)           # Dex = 100
    val = set_bits(val, 66, 10, 250)           # Vit = 250
    val = set_bits(val, 102, 21, hp * 256)     # HP
    val = set_bits(val, 132, 21, hp * 256)     # MaxHP
    val = set_bits(val, 162, 21, mp * 256)     # MP
    val = set_bits(val, 192, 21, mp * 256)     # MaxMP
    raw[gf + 2 : if_off] = val.to_bytes(nbytes, 'little')
    if strip_staff:
        jm = raw.find(b'JM')
        cnt = struct.unpack_from('<H', raw, jm + 2)[0]
        if raw[0x3A2:0x3A4] != b'JM':
            raise ValueError('unexpected staff item offset in sorceress template')
        del raw[0x3A2:0x3BC]
        struct.pack_into('<H', raw, jm + 2, cnt - 1)
    if dead_rogue_merc:
        # Pre-save a dead Act 1 Rogue Scout merc so Kashya exercises live C2S 0x62 ResurrectMerc.
        kf = raw.find(b'kf')
        jf = raw.rfind(b'jf', 0, kf)
        struct.pack_into('<HIHHI', raw, 0xB1, 1, 0x12345678, 0, 0, 50000)
        raw = raw[: jf + 2] + b'JM\x00\x00' + raw[jf + 2 :]
    return fix_d2s_checksum(raw)


def gzip_deterministic(data: bytes) -> bytes:
    buf = io.BytesIO()
    with gzip.GzipFile(filename='', mode='wb', fileobj=buf, compresslevel=9, mtime=0) as gz:
        gz.write(data)
    return buf.getvalue()


def to_inputs(pairs: list[tuple[int, str]]) -> list[dict]:
    return [{'frame': f, 'c2s': hx} for f, hx in pairs]


