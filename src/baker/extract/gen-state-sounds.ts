/**
 * Generates src/common/audio/state-sounds-113c.ts from the 1.13c States.txt `onsound` / `offsound` columns
 * (resolved to Sounds.txt ids through `SOUNDS_BY_NAME_113C`).
 *
 * D2Client.dll `0x6fb23760` (client state set, called per state by the S2C 0xA7/0xA8/0xAA handlers, e.g. 0x6fb5dc03):
 *   `if (!STATES_CheckState(pUnit, nState))` (0x6fabc1fc @ 0x6fb237d6) and `StatesTxt[nState].wOnSound >= 0`
 *   (`movsx ebx, word [edi+0x26]` @ 0x6fb237fc) → `PlaySound(wOnSound, pUnit, 0, 0, 0)` (0x6fb38a70 @ 0x6fb2380f),
 *   then `STATES_ToggleState(pUnit, nState, 1)`. The on-sound therefore plays once per inactive → active transition.
 *
 * Usage: npm run extract:state-sounds   (MPQs from D2_DATA_DIR or samples/d2)
 */
import { writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { pathToFileURL } from 'node:url'
import { SOUNDS_BY_NAME_113C } from '../../common/audio/sounds-113c.ts'
import { DEFAULT_NODE_MPQ_DIR, NodeMpqArchiveSource } from '../mpq-archive-source.ts'

export interface ExtractedStateSoundRow113c {
  readonly stateId: number
  readonly state: string
  readonly onSound: number
  readonly offSound: number
}

function resolveSoundName(name: string, column: string, state: string): number {
  const key = name.trim().toLowerCase()
  if (key === '') return 0
  const id = SOUNDS_BY_NAME_113C[key]
  if (id === undefined || id <= 0) {
    throw new Error(`States.txt ${state}.${column} = "${name}" does not resolve to a Sounds.txt id`)
  }
  return id
}

/** Parses States.txt bytes and returns every state row that has an onsound or offsound. */
export function extractStateSoundRows113c(statesTxt: Uint8Array): ExtractedStateSoundRow113c[] {
  const lines = new TextDecoder('latin1').decode(statesTxt).split(/\r?\n/).filter((l) => l.length > 0)
  if (lines.length === 0) throw new Error('States.txt is empty')
  const headers = lines[0]!.split('\t').map((h) => h.trim())
  const col = (name: string): number => {
    const idx = headers.indexOf(name)
    if (idx < 0) throw new Error(`States.txt is missing column "${name}"`)
    return idx
  }
  const cState = col('state')
  const cId = col('id')
  const cOn = col('onsound')
  const cOff = col('offsound')
  const out: ExtractedStateSoundRow113c[] = []
  for (let i = 1; i < lines.length; i += 1) {
    const cells = lines[i]!.split('\t')
    const state = (cells[cState] ?? '').trim()
    if (state === '') continue
    const stateId = Number((cells[cId] ?? '').trim())
    if (!Number.isInteger(stateId) || stateId !== i - 1) {
      throw new Error(`States.txt row ${String(i)} (${state}) has id ${String(cells[cId])}, expected ${String(i - 1)}`)
    }
    const onSound = resolveSoundName(cells[cOn] ?? '', 'onsound', state)
    const offSound = resolveSoundName(cells[cOff] ?? '', 'offsound', state)
    if (onSound > 0 || offSound > 0) out.push({ stateId, state, onSound, offSound })
  }
  return out
}

export function renderStateSoundsModule113c(rows: readonly ExtractedStateSoundRow113c[]): string {
  const lines: string[] = [
    '// AUTO-GENERATED by src/baker/extract/gen-state-sounds.ts — DO NOT EDIT MANUALLY.',
    '// Source of truth: Diablo II v1.13c States.txt (onsound / offsound) resolved through Sounds.txt.',
    '',
    'export interface StateSoundRow113c {',
    '  readonly stateId: number',
    '  readonly state: string',
    '  readonly onSound: number',
    '  readonly offSound: number',
    '}',
    '',
    'export const STATE_SOUNDS_113C: readonly StateSoundRow113c[] = [',
    ...rows.map(
      (r) =>
        `  { stateId: ${String(r.stateId)}, state: ${JSON.stringify(r.state)}, onSound: ${String(r.onSound)}, offSound: ${String(r.offSound)} },`,
    ),
    ']',
    '',
    'const STATE_SOUNDS_BY_ID_113C: ReadonlyMap<number, StateSoundRow113c> = new Map(',
    '  STATE_SOUNDS_113C.map((row) => [row.stateId, row] as const),',
    ')',
    '',
    '/** States.txt `onsound` (Sounds.txt id) for a state, or 0 when the state has none. */',
    'export function getStateOnSound113c(stateId: number): number {',
    '  return STATE_SOUNDS_BY_ID_113C.get(stateId)?.onSound ?? 0',
    '}',
    '',
    '/** States.txt `offsound` (Sounds.txt id) for a state, or 0 when the state has none. */',
    'export function getStateOffSound113c(stateId: number): number {',
    '  return STATE_SOUNDS_BY_ID_113C.get(stateId)?.offSound ?? 0',
    '}',
    '',
  ]
  return lines.join('\n')
}

function main(): void {
  const archives = new NodeMpqArchiveSource(DEFAULT_NODE_MPQ_DIR)
  const bytes = archives.mounted.readFile('data\\global\\excel\\States.txt')
  if (!bytes) throw new Error(`States.txt not found in MPQs at ${DEFAULT_NODE_MPQ_DIR}`)
  const rows = extractStateSoundRows113c(bytes)
  const target = resolve('src/common/audio/state-sounds-113c.ts')
  writeFileSync(target, renderStateSoundsModule113c(rows))
  console.log(`wrote ${target} (${String(rows.length)} states) from ${DEFAULT_NODE_MPQ_DIR}`)
}

if (process.argv[1] !== undefined && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  main()
}
