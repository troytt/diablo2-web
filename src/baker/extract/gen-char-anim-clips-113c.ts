/**
 * Generate `src/common/units/char-anim-clips-113c.generated.ts` from `data\global\AnimData.D2`.
 *
 * Emits every player-class COF record (`<token><mode><wclass>`, 7 tokens x 18 clip modes x 14
 * weapon classes) that exists in AnimData.D2, with the same first-record-wins rule the game uses
 * (D2Common `#10385` 0x6FD91EF0 -> hash-block scan 0x6FD91DD0). `char-anim-speed.ts` builds
 * `CHAR_ANIM_CLIPS_113C` / `CHAR_WCLASS_ANIM_CLIPS_113C` from it, so the tables are never hand-edited.
 *
 * Usage: npx tsx src/baker/extract/gen-char-anim-clips-113c.ts [archiveDir]
 */
import { writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { getSharedMountedArchives } from '../mpq-archive-source.ts'
import { decodeAnimDataFile } from '../../common/formats/animdata.ts'

const HERE = dirname(fileURLToPath(import.meta.url))
const OUT = resolve(HERE, '../../common/units/char-anim-clips-113c.generated.ts')
const TOKENS = ['AM', 'SO', 'NE', 'PA', 'BA', 'DZ', 'AI'] as const
const MODES = ['DT', 'NU', 'WL', 'RN', 'GH', 'TN', 'TW', 'A1', 'A2', 'BL', 'SC', 'TH', 'KK', 'S1', 'S2', 'S3', 'S4', 'DD'] as const
const WCLASSES = ['HTH', 'BOW', '1HS', '1HT', 'STF', '2HS', '2HT', 'XBW', '1JS', '1JT', '1SS', '1ST', 'HT1', 'HT2'] as const

async function main(): Promise<void> {
  const archives = process.argv[2] ? getSharedMountedArchives(process.argv[2]) : getSharedMountedArchives()
  const raw = await archives.read('data\\global\\AnimData.D2')
  const file = decodeAnimDataFile(raw)
  const lines: string[] = []
  let n = 0
  for (const t of TOKENS) {
    for (const m of MODES) {
      for (const w of WCLASSES) {
        const name = `${t}${m}${w}`
        const rec = file.records.get(name)
        if (!rec) continue
        const ev = rec.events.map(e => `[${e.frame}, ${e.code}]`).join(', ')
        lines.push(`  ${name}: [${rec.framesPerDirection}, ${rec.animationSpeed}, [${ev}]],`)
        n++
      }
    }
  }
  const text = [
    '/**',
    ' * GENERATED by src/baker/extract/gen-char-anim-clips-113c.ts from data\\global\\AnimData.D2 (1.13c).',
    ' * Do not edit by hand. Player COF records `<token><mode><wclass>`: [framesPerDirection, speed, events],',
    ' * events = [frame, code] (1 = attack, 2 = missile). First record wins for repeated names, like',
    ' * D2Common #10385 (0x6FD91EF0).',
    ' */',
    'export type AnimDataClipTuple113c = readonly [number, number, readonly (readonly [number, number])[]]',
    '',
    `/** ${n} records. */`,
    'export const ANIMDATA_PLAYER_CLIPS_113C: Readonly<Record<string, AnimDataClipTuple113c>> = {',
    ...lines,
    '}',
    '',
  ].join('\n')
  writeFileSync(OUT, text)
  process.stdout.write(`wrote ${join('src/common/units', 'char-anim-clips-113c.generated.ts')} (${n} records)\n`)
}

void main()
