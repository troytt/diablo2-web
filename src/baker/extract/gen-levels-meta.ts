/**
 * Generates src/common/world/levels-meta.ts from the 1.13c `data\global\excel\Levels.txt`
 * (Patch_D2.mpq wins over d2exp.mpq / d2data.mpq through the normal mount order).
 *
 * One record per level id 1..136 with the columns the client needs at runtime:
 *   Name, LevelName, Act (+1), IsInside, Intensity, Red, Green, Blue, NoPer, Rain, Mud.
 *
 * Rain / Mud drive the client weather (D2Client 0x6fb31340 reads them through
 * D2Common #10215 / #10499; see docs/weather_113c.md).
 *
 * Empty numeric cells read as 0, which is how the game's own txt compiler treats them.
 * Any other non-integer cell, a missing column, a duplicate id or a missing id fails the run.
 *
 * Usage: npm run extract:levels-meta   (MPQs from D2_DATA_DIR or samples/d2)
 */
import { writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { pathToFileURL } from 'node:url'
import { cell, parseTable, type D2Table } from '../../common/world/acts.ts'
import { DEFAULT_NODE_MPQ_DIR, mountNodeArchives } from '../mpq-archive-source.ts'

const LEVELS_MEMBER = 'data\\global\\excel\\levels.txt'
const FIRST_LEVEL_ID = 1
const LAST_LEVEL_ID = 136
const REQUIRED_COLUMNS = [
  'Name', 'Id', 'Act', 'IsInside', 'Intensity', 'Red', 'Green', 'Blue', 'NoPer', 'Rain', 'Mud', 'LevelName',
] as const

interface LevelRow {
  readonly id: number
  readonly name: string
  readonly levelName: string
  readonly act: number
  readonly isInside: boolean
  readonly intensity: number
  readonly red: number
  readonly green: number
  readonly blue: number
  readonly noPer: boolean
  readonly rain: boolean
  readonly mud: boolean
}

function intCell(table: D2Table, row: readonly string[], column: string, id: string): number {
  const raw = cell(table, row, column).trim()
  if (raw === '') return 0
  if (!/^-?\d+$/.test(raw)) throw new Error(`Levels.txt Id=${id}: column ${column} is not an integer: '${raw}'`)
  return Number(raw)
}

function flagCell(table: D2Table, row: readonly string[], column: string, id: string): boolean {
  const value = intCell(table, row, column, id)
  if (value !== 0 && value !== 1) throw new Error(`Levels.txt Id=${id}: column ${column} must be 0 or 1, got ${value}`)
  return value === 1
}

/** Prettier-style quoting: single quotes unless the text contains one. */
function quote(text: string): string {
  if (text.includes('\\') || text.includes('\n')) throw new Error(`unsupported character in '${text}'`)
  if (!text.includes("'")) return `'${text}'`
  if (text.includes('"')) throw new Error(`string contains both quote kinds: ${text}`)
  return `"${text}"`
}

export function readLevelRows(table: D2Table): LevelRow[] {
  for (const column of REQUIRED_COLUMNS) {
    if (!table.header.includes(column)) throw new Error(`Levels.txt has no column ${column}`)
  }
  const byId = new Map<number, LevelRow>()
  for (const row of table.rows) {
    const idText = cell(table, row, 'Id').trim()
    if (!/^\d+$/.test(idText)) continue // the "Expansion" separator row has no id
    const id = Number(idText)
    if (id < FIRST_LEVEL_ID || id > LAST_LEVEL_ID) continue // 0 = Null row
    if (byId.has(id)) throw new Error(`Levels.txt: duplicate Id=${id}`)
    const act = intCell(table, row, 'Act', idText)
    if (act < 0 || act > 4) throw new Error(`Levels.txt Id=${id}: Act ${act} out of range 0..4`)
    byId.set(id, {
      id,
      // String cells are trimmed: Levels.txt row 52 stores 'Palace Cellar Level 1 ' with a trailing
      // space, and every consumer (waypoint names, TBL supplements) keys on the trimmed text.
      name: cell(table, row, 'Name').trim(),
      levelName: cell(table, row, 'LevelName').trim(),
      act: act + 1,
      isInside: flagCell(table, row, 'IsInside', idText),
      intensity: intCell(table, row, 'Intensity', idText),
      red: intCell(table, row, 'Red', idText),
      green: intCell(table, row, 'Green', idText),
      blue: intCell(table, row, 'Blue', idText),
      noPer: flagCell(table, row, 'NoPer', idText),
      rain: flagCell(table, row, 'Rain', idText),
      mud: flagCell(table, row, 'Mud', idText),
    })
  }
  const rows: LevelRow[] = []
  for (let id = FIRST_LEVEL_ID; id <= LAST_LEVEL_ID; id += 1) {
    const row = byId.get(id)
    if (!row) throw new Error(`Levels.txt: missing Id=${id}`)
    rows.push(row)
  }
  return rows
}

export function renderLevelsMeta(rows: readonly LevelRow[]): string {
  const lines: string[] = [
    '/**',
    ' * Authentic Diablo II v1.13c Level Lighting & Ambient Metadata.',
    ' * Extracted directly from 1.13c Patch_D2.mpq data\\\\global\\\\excel\\\\Levels.txt.',
    ' * Enforces Zero Runtime MPQ/DLL Architectural Invariant.',
    ' *',
    ' * GENERATED by src/baker/extract/gen-levels-meta.ts (`npm run extract:levels-meta`). Do not edit by hand.',
    ' */',
    '',
    'export interface LevelLightingDef {',
    '  /** 1.13c Levels.txt Id (1..136) */',
    '  readonly id: number',
    '  /** Levels.txt Name */',
    '  readonly name: string',
    '  /** Levels.txt LevelName (in-game display key) */',
    '  readonly levelName: string',
    '  /** Act number (1..5) */',
    '  readonly act: number',
    '  /** Whether the level is an indoor/underground dungeon (1 = indoor, 0 = outdoor) */',
    '  readonly isInside: boolean',
    '  /** Base light intensity (0..255). 75 indoor levels are 0; outdoors driven by ENVIRONMENT cycle */',
    '  readonly intensity: number',
    '  /** Red lighting component (0..255) */',
    '  readonly red: number',
    '  /** Green lighting component (0..255) */',
    '  readonly green: number',
    '  /** Blue lighting component (0..255) */',
    '  readonly blue: number',
    '  /** Whether perspective mode is disabled for this level (NoPer == 1) */',
    '  readonly noPer: boolean',
    '  /**',
    '   * Levels.txt Rain: client precipitation runs here (rain; snow in Act V). Read by D2Client 0x6fb31340',
    '   * through D2Common #10215.',
    '   */',
    '  readonly rain: boolean',
    '  /** Levels.txt Mud: mud bubbles spawn on visible water floor tiles. Read through D2Common #10499. */',
    '  readonly mud: boolean',
    '}',
    '',
    'export const CANONICAL_LEVEL_LIGHTING: Readonly<Record<number, LevelLightingDef>> = Object.freeze({',
  ]
  for (const row of rows) {
    lines.push(
      `  ${row.id}: {`,
      `    id: ${row.id},`,
      `    name: ${quote(row.name)},`,
      `    levelName: ${quote(row.levelName)},`,
      `    act: ${row.act},`,
      `    isInside: ${String(row.isInside)},`,
      `    intensity: ${row.intensity},`,
      `    red: ${row.red},`,
      `    green: ${row.green},`,
      `    blue: ${row.blue},`,
      `    noPer: ${String(row.noPer)},`,
      `    rain: ${String(row.rain)},`,
      `    mud: ${String(row.mud)},`,
      '  },',
    )
  }
  lines.push(
    '})',
    '',
    '/**',
    ' * Helper to retrieve authentic 1.13c lighting definition for any level ID.',
    ' */',
    'export function getLevelLighting(levelId: number): LevelLightingDef | undefined {',
    '  return CANONICAL_LEVEL_LIGHTING[levelId]',
    '}',
    '',
  )
  return lines.join('\n')
}

async function main(): Promise<void> {
  const archives = mountNodeArchives(DEFAULT_NODE_MPQ_DIR)
  const table = parseTable(await archives.read(LEVELS_MEMBER))
  const rows = readLevelRows(table)
  const target = resolve('src/common/world/levels-meta.ts')
  writeFileSync(target, renderLevelsMeta(rows))
  const rainIds = rows.filter(r => r.rain).map(r => r.id)
  const mudIds = rows.filter(r => r.mud).map(r => r.id)
  console.log(`wrote ${target}: ${rows.length} levels; Rain=[${rainIds.join(',')}] Mud=[${mudIds.join(',')}]`)
}

if (process.argv[1] !== undefined && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  await main()
}
