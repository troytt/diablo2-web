/**
 * Baker extractor (`src/baker/extract/gen-level-mon-region-113c.ts`):
 * Generates `src/server/world/level-mon-region-113c.ts` from 1.13c MPQ binary tables
 * (`levels.bin`, `monstats.bin`, `objects.txt`) for exact `MONSTER_InitAllRegions` (`0x6FCEACC0`),
 * `OBJECTS_PopulateRoom` (`0x6FC4F0D0`), and `MONSTER_PopulateRoom` (`0x6FC67A20`) parity.
 */

import { writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { DEFAULT_NODE_MPQ_DIR, mountNodeArchives } from '../mpq-archive-source.ts'
import { cell, parseTable } from '../../common/world/acts.ts'

async function main(): Promise<void> {
  const archives = mountNodeArchives(DEFAULT_NODE_MPQ_DIR)
  const lvlBin = Buffer.from(await archives.read('data\\global\\excel\\levels.bin'))
  const monBin = Buffer.from(await archives.read('data\\global\\excel\\monstats.bin'))
  const mon2Bin = Buffer.from(await archives.read('data\\global\\excel\\monstats2.bin'))
  const objTbl = parseTable(await archives.read('data\\global\\excel\\objects.txt'))

  const nLevels = lvlBin.readUInt32LE(0)
  const lvlRecSz = Math.trunc((lvlBin.length - 4) / nLevels)
  const nMons = monBin.readUInt32LE(0)
  const monRecSz = Math.trunc((monBin.length - 4) / nMons)
  const nMons2 = mon2Bin.readUInt32LE(0)
  const mon2RecSz = Math.trunc((mon2Bin.length - 4) / nMons2)

  const lines: string[] = [
    '/**',
    ' * Auto-generated by `src/baker/extract/gen-level-mon-region-113c.ts` from 1.13c MPQ',
    ' * `data\\global\\excel\\levels.bin`, `monstats.bin`, and `objects.txt`. Do not edit by hand.',
    ' */',
    '',
    'export interface LevelMonRegionSpec113c {',
    '  readonly minWarpDistSq: number',
    '  readonly monLvlEx: readonly [number, number, number]',
    '  readonly monDen: readonly [number, number, number]',
    '  readonly monUMin: readonly [number, number, number]',
    '  readonly monUMax: readonly [number, number, number]',
    '  readonly rangedSpawn: number',
    '  readonly numMon: number',
    '  readonly monPool: readonly number[]',
    '  readonly nmonPool: readonly number[]',
    '}',
    '',
    '/** Indexed by `levelId` (`0..136`; index `0` is `null`). */',
    'export const LEVEL_MON_REGION_113C: readonly (LevelMonRegionSpec113c | null)[] = [',
    '  null,',
  ]

  for (let lid = 1; lid < nLevels; lid++) {
    const off = 4 + lid * lvlRecSz
    const minWarpDistSq = lvlBin.readInt32LE(off + 0x0c)
    const monLvlEx: [number, number, number] = [
      lvlBin.readInt16LE(off + 0x16),
      lvlBin.readInt16LE(off + 0x18),
      lvlBin.readInt16LE(off + 0x1a),
    ]
    const monDen: [number, number, number] = [
      lvlBin.readInt32LE(off + 0x1c),
      lvlBin.readInt32LE(off + 0x20),
      lvlBin.readInt32LE(off + 0x24),
    ]
    const monUMin: [number, number, number] = [
      lvlBin.readUInt8(off + 0x28),
      lvlBin.readUInt8(off + 0x29),
      lvlBin.readUInt8(off + 0x2a),
    ]
    const monUMax: [number, number, number] = [
      lvlBin.readUInt8(off + 0x2b),
      lvlBin.readUInt8(off + 0x2c),
      lvlBin.readUInt8(off + 0x2d),
    ]
    const rangedSpawn = lvlBin.readUInt8(off + 0x31)
    const numMon = lvlBin.readUInt8(off + 0x32)
    const monPool: number[] = []
    for (let i = 0; i < 25; i++) {
      const m = lvlBin.readInt16LE(off + 0x36 + i * 2)
      if (m < 0) break
      monPool.push(m)
    }
    const nmonPool: number[] = []
    for (let i = 0; i < 25; i++) {
      const m = lvlBin.readInt16LE(off + 0x68 + i * 2)
      if (m < 0) break
      nmonPool.push(m)
    }
    lines.push(
      `  { minWarpDistSq: ${minWarpDistSq}, monLvlEx: [${monLvlEx.join(', ')}], monDen: [${monDen.join(', ')}], monUMin: [${monUMin.join(', ')}], monUMax: [${monUMax.join(', ')}], rangedSpawn: ${rangedSpawn}, numMon: ${numMon}, monPool: [${monPool.join(', ')}], nmonPool: [${nmonPool.join(', ')}] },`,
    )
  }
  lines.push(']')
  lines.push('')

  // Compact monster spawn eligibility & idle-wander tuple: [canSpawn (0|1), rangedType (0|1), rarity, idleWander (0|1)]
  lines.push(
    '/** Indexed by `hcIdx` (`0..733`): `[canSpawn (0|1), rangedType (0|1), rarity, idleWander (0|1)]` from `monstats.bin` + `monstats2.bin`. */',
  )
  lines.push(
    'export const MONSTATS_SPAWN_META_113C: readonly (readonly [number, number, number, number])[] = [',
  )
  for (let hc = 0; hc < nMons; hc++) {
    const off = 4 + hc * monRecSz
    const fByte0 = monBin.readUInt8(off + 0x0c)
    const fByte3 = monBin.readUInt8(off + 0x0f)
    const rarity = monBin.readUInt8(off + 0x2e)
    const wMonStatsEx = monBin.readInt16LE(off + 0x18)
    const canSpawn = (fByte0 & 0x01) !== 0 ? 1 : 0
    const rangedType = (fByte3 & 0x02) !== 0 ? 1 : 0
    const idleWander =
      wMonStatsEx >= 0 &&
      wMonStatsEx < nMons2 &&
      (mon2Bin.readUInt8(4 + wMonStatsEx * mon2RecSz + 0xf0) & 0x04) !== 0
        ? 1
        : 0
    lines.push(`  [${canSpawn}, ${rangedType}, ${rarity}, ${idleWander}],`)
  }
  lines.push(']')
  lines.push('')

  // Compact object population tuple: [sizeX, sizeY, hasCol0, initFn, popFn, preOperate, beta, subClass, parm0]
  lines.push(
    '/** Indexed by `Objects.txt` `cid` (`0..572`): `[sizeX, sizeY, hasCol0, initFn, popFn, preOperate, beta, subClass, parm0]`. */',
  )
  lines.push(
    'export const OBJECT_POPULATE_META_113C: readonly (readonly [number, number, number, number, number, number, number, number, number])[] = [',
  )
  const num = (r: readonly string[], col: string): number => {
    const s = cell(objTbl, r, col).trim()
    return s === '' ? 0 : Number(s)
  }
  for (const r of objTbl.rows) {
    if (r[0] === 'Expansion') continue
    lines.push(
      `  [${num(r, 'SizeX')}, ${num(r, 'SizeY')}, ${num(r, 'HasCollision0')}, ${num(r, 'InitFn')}, ${num(r, 'PopulateFn')}, ${num(r, 'PreOperate')}, ${num(r, 'Beta')}, ${num(r, 'SubClass')}, ${num(r, 'Parm0')}],`,
    )
  }
  lines.push(']')
  lines.push('')

  const here = dirname(fileURLToPath(import.meta.url))
  const outPath = resolve(here, '../../server/world/level-mon-region-113c.ts')
  writeFileSync(outPath, lines.join('\n'), 'utf8')
  console.log(`Wrote ${outPath} (${nLevels - 1} levels, ${nMons} monsters)`)
}

main().catch((err) => {
  console.error(err)
  process.exit(1)
})
