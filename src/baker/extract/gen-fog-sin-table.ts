/**
 * Generates src/client/weather/fog-sin-table.ts from the 1.13c Fog.dll.
 *
 * Fog #10084 (sin, Fog 0x6ff66710) and #10083 (cos, Fog 0x6ff66730) index a static 512-entry f32
 * table at Fog 0x6ff7f470 (file offset 0x2f470). The table is NOT `fround(sin(2πi/512))`: 328 of the
 * 512 entries differ by one ulp and T[256] is -8.742278e-08, so the client weather port embeds the
 * exact bit patterns to keep every trunc() boundary of the original.
 *
 * Usage: npm run extract:fog-sin   (Fog.dll from D2_DATA_DIR or samples/d2)
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { pathToFileURL } from 'node:url'
import { DEFAULT_NODE_MPQ_DIR } from '../mpq-archive-source.ts'

const TABLE_FILE_OFFSET = 0x2f470
const TABLE_ENTRIES = 512

/** Reads the 512 table entries as u32 bit patterns and checks the known anchors. */
export function readFogSinTable(fogDll: Uint8Array): number[] {
  if (fogDll.length < TABLE_FILE_OFFSET + TABLE_ENTRIES * 4) {
    throw new Error(`Fog.dll is ${fogDll.length} bytes, too short for the sine table at 0x${TABLE_FILE_OFFSET.toString(16)}`)
  }
  const view = new DataView(fogDll.buffer, fogDll.byteOffset + TABLE_FILE_OFFSET, TABLE_ENTRIES * 4)
  const bits: number[] = []
  for (let i = 0; i < TABLE_ENTRIES; i += 1) bits.push(view.getUint32(i * 4, true))
  const anchors: readonly [number, number][] = [
    [0, 0x00000000],
    [7, 0x3dafb681],
    [128, 0x3f800000],
    [256, 0xb3bbbd2e],
    [384, 0xbf800000],
  ]
  for (const [index, expected] of anchors) {
    if (bits[index] !== expected) {
      throw new Error(
        `Fog.dll sine table T[${index}] = 0x${bits[index]!.toString(16)}, expected 0x${expected.toString(16)} (not the 1.13c Fog.dll?)`,
      )
    }
  }
  return bits
}

export function renderFogSinTable(bits: readonly number[]): string {
  const rows: string[] = []
  for (let i = 0; i < bits.length; i += 8) {
    rows.push(`  ${bits.slice(i, i + 8).map(b => `0x${b.toString(16).padStart(8, '0')}`).join(', ')},`)
  }
  return [
    '/**',
    ' * Fog.dll 1.13c sine table (Fog 0x6ff7f470, file offset 0x2f470): 512 f32 entries, one turn.',
    ' * GENERATED by src/baker/extract/gen-fog-sin-table.ts (`npm run extract:fog-sin`). Do not edit by hand.',
    ' *',
    ' * The values are the exact f32 bit patterns of the original table. They are not',
    ' * `Math.fround(Math.sin(2 * Math.PI * i / 512))`: 328 entries differ by one ulp and T[256] is',
    ' * -8.742278e-08, and the weather code truncates products of these values toward zero.',
    ' */',
    '',
    'const FOG_SIN_TABLE_BITS: readonly number[] = [',
    ...rows,
    ']',
    '',
    'function decodeTable(bits: readonly number[]): Float64Array {',
    '  const view = new DataView(new ArrayBuffer(4))',
    '  const out = new Float64Array(bits.length)',
    '  for (let i = 0; i < bits.length; i += 1) {',
    '    view.setUint32(0, bits[i]!, true)',
    '    out[i] = view.getFloat32(0, true)',
    '  }',
    '  return out',
    '}',
    '',
    '/** The table as JS numbers; every value is exactly representable as f32. */',
    'export const FOG_SIN_TABLE: Readonly<Float64Array> = decodeTable(FOG_SIN_TABLE_BITS)',
    '',
    '/** Fog #10084 (Fog 0x6ff66710): `T[a & 511]`, 512 units per turn. */',
    'export function fogSin(angle: number): number {',
    '  return FOG_SIN_TABLE[angle & 511]!',
    '}',
    '',
    '/** Fog #10083 (Fog 0x6ff66730): `T[(a + 128) & 511]`. */',
    'export function fogCos(angle: number): number {',
    '  return FOG_SIN_TABLE[(angle + 128) & 511]!',
    '}',
    '',
  ].join('\n')
}

function main(): void {
  const fogPath = join(DEFAULT_NODE_MPQ_DIR, 'Fog.dll')
  if (!existsSync(fogPath)) throw new Error(`Fog.dll not found at ${fogPath} (set D2_DATA_DIR)`)
  const bits = readFogSinTable(new Uint8Array(readFileSync(fogPath)))
  const target = resolve('src/client/weather/fog-sin-table.ts')
  writeFileSync(target, renderFogSinTable(bits))
  console.log(`wrote ${target} from ${fogPath}`)
}

if (process.argv[1] !== undefined && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  main()
}
