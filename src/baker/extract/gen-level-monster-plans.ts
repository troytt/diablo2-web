/**
 * Generates src/common/world/level-monster-plans.ts from the 1.13c `data\global\excel\Levels.txt`
 * (Patch_D2.mpq wins over d2exp.mpq / d2data.mpq through the normal mount order).
 *
 * One record per level id 1..136 carrying the monster-population columns the authoritative
 * server (`GameInstance` room streaming, #1327) needs at runtime without mounting MPQs:
 *   NumMon, MonDen / MonDen(N) / MonDen(H), MonUMin*, MonUMax*, MonLvl1Ex / MonLvl2Ex / MonLvl3Ex,
 *   MonWndr, mon1..mon10, nmon1..nmon10, umon1..umon10.
 *
 * Every column is read through `readLevelMonsterPlan` (src/common/units/monsters-data.ts), the same
 * reader the bake (`planLevelMonsters`) and tools/verify-monsters.ts use, so the embedded table and
 * the archive-backed path cannot disagree. Every pool entry must resolve to a canonical
 * `MonStats.txt` row; an unknown id, a missing level or a missing column fails the run.
 *
 * Usage: npm run extract:level-monster-plans   (MPQs from D2_DATA_DIR or samples/d2)
 */
import { writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { pathToFileURL } from 'node:url'
import { getCanonicalMonsterKinds, readLevelMonsterPlan, type Difficulty } from '../../common/units/monsters-data.ts'
import { parseTable, type D2Table } from '../../common/world/acts.ts'
import { DEFAULT_NODE_MPQ_DIR, mountNodeArchives } from '../mpq-archive-source.ts'

const LEVELS_MEMBER = 'data\\global\\excel\\levels.txt'
const FIRST_LEVEL_ID = 1
const LAST_LEVEL_ID = 136
const DIFFICULTIES: readonly Difficulty[] = ['normal', 'nightmare', 'hell']
const REQUIRED_COLUMNS = [
  'Id', 'Name', 'NumMon', 'MonWndr',
  'MonDen', 'MonDen(N)', 'MonDen(H)',
  'MonUMin', 'MonUMin(N)', 'MonUMin(H)',
  'MonUMax', 'MonUMax(N)', 'MonUMax(H)',
  'MonLvl1Ex', 'MonLvl2Ex', 'MonLvl3Ex',
  'mon1', 'nmon1', 'umon1',
] as const

export interface LevelMonsterPlanRow {
  readonly id: number
  readonly name: string
  readonly typeCount: number
  readonly wander: boolean
  readonly density: readonly [number, number, number]
  readonly eliteMin: readonly [number, number, number]
  readonly eliteMax: readonly [number, number, number]
  readonly monsterLevel: readonly [number, number, number]
  readonly pool: readonly string[]
  readonly nightmarePool: readonly string[]
  readonly elitePool: readonly string[]
}

function quote(text: string): string {
  if (text.includes('\\') || text.includes('\n')) throw new Error(`unsupported character in '${text}'`)
  if (!text.includes("'")) return `'${text}'`
  if (text.includes('"')) throw new Error(`string contains both quote kinds: ${text}`)
  return `"${text}"`
}

export function readLevelMonsterPlanRows(table: D2Table): LevelMonsterPlanRow[] {
  for (const column of REQUIRED_COLUMNS) {
    if (!table.header.includes(column)) throw new Error(`Levels.txt has no column ${column}`)
  }
  const kinds = getCanonicalMonsterKinds('normal')
  const rows: LevelMonsterPlanRow[] = []
  for (let id = FIRST_LEVEL_ID; id <= LAST_LEVEL_ID; id += 1) {
    const plans = DIFFICULTIES.map(d => readLevelMonsterPlan(table, id, d))
    const [n, nm, h] = plans
    if (!n || !nm || !h) throw new Error(`Levels.txt: missing Id=${id}`)
    for (const name of [...n.pool, ...n.nightmarePool, ...n.elitePool]) {
      if (!kinds.has(name)) throw new Error(`Levels.txt Id=${id}: monster '${name}' is not a MonStats.txt Id`)
    }
    rows.push({
      id,
      name: n.levelName,
      typeCount: n.typeCount,
      wander: n.wander,
      density: [n.density, nm.density, h.density],
      eliteMin: [n.eliteMin, nm.eliteMin, h.eliteMin],
      eliteMax: [n.eliteMax, nm.eliteMax, h.eliteMax],
      monsterLevel: [n.monsterLevel, nm.monsterLevel, h.monsterLevel],
      pool: n.pool,
      nightmarePool: n.nightmarePool,
      elitePool: n.elitePool,
    })
  }
  return rows
}

function list(values: readonly string[]): string {
  return `[${values.map(quote).join(', ')}]`
}

function triple(values: readonly [number, number, number]): string {
  return `[${values[0]}, ${values[1]}, ${values[2]}]`
}

export function renderLevelMonsterPlans(rows: readonly LevelMonsterPlanRow[]): string {
  const lines: string[] = [
    '/**',
    ' * Authentic Diablo II v1.13c per-level monster population columns (#1327).',
    ' * Extracted directly from 1.13c Patch_D2.mpq data\\\\global\\\\excel\\\\Levels.txt through',
    ' * `readLevelMonsterPlan` (src/common/units/monsters-data.ts).',
    ' * Enforces Zero Runtime MPQ/DLL Architectural Invariant.',
    ' *',
    ' * GENERATED by src/baker/extract/gen-level-monster-plans.ts (`npm run extract:level-monster-plans`).',
    ' * Do not edit by hand.',
    ' */',
    '',
    "import type { Difficulty, LevelMonsterPlan } from '../units/monsters-data.ts'",
    '',
    'export interface LevelMonsterPlanRecord {',
    '  /** Levels.txt Id (1..136) */',
    '  readonly id: number',
    '  /** Levels.txt Name */',
    '  readonly name: string',
    '  /** NumMon: how many distinct types are drawn from the pool */',
    '  readonly typeCount: number',
    '  /** MonWndr */',
    '  readonly wander: boolean',
    '  /** MonDen / MonDen(N) / MonDen(H) */',
    '  readonly density: readonly [number, number, number]',
    '  /** MonUMin / MonUMin(N) / MonUMin(H) */',
    '  readonly eliteMin: readonly [number, number, number]',
    '  /** MonUMax / MonUMax(N) / MonUMax(H) */',
    '  readonly eliteMax: readonly [number, number, number]',
    '  /** MonLvl1Ex / MonLvl2Ex / MonLvl3Ex */',
    '  readonly monsterLevel: readonly [number, number, number]',
    '  /** mon1..mon10 (blanks dropped) */',
    '  readonly pool: readonly string[]',
    '  /** nmon1..nmon10 (blanks dropped) */',
    '  readonly nightmarePool: readonly string[]',
    '  /** umon1..umon10 (blanks dropped) */',
    '  readonly elitePool: readonly string[]',
    '}',
    '',
    'export const CANONICAL_LEVEL_MONSTER_PLANS: Readonly<Record<number, LevelMonsterPlanRecord>> = Object.freeze({',
  ]
  for (const row of rows) {
    lines.push(
      `  ${row.id}: {`,
      `    id: ${row.id},`,
      `    name: ${quote(row.name)},`,
      `    typeCount: ${row.typeCount},`,
      `    wander: ${String(row.wander)},`,
      `    density: ${triple(row.density)},`,
      `    eliteMin: ${triple(row.eliteMin)},`,
      `    eliteMax: ${triple(row.eliteMax)},`,
      `    monsterLevel: ${triple(row.monsterLevel)},`,
      `    pool: ${list(row.pool)},`,
      `    nightmarePool: ${list(row.nightmarePool)},`,
      `    elitePool: ${list(row.elitePool)},`,
      '  },',
    )
  }
  lines.push(
    '})',
    '',
    '/**',
    ' * Return the 1.13c `LevelMonsterPlan` (same shape `readLevelMonsterPlan` builds from Levels.txt)',
    ' * for one level and difficulty, or null when the id is not a Levels.txt row (1..136).',
    ' */',
    'export function getLevelMonsterPlan113c(levelId: number, difficulty: Difficulty): LevelMonsterPlan | null {',
    '  const rec = CANONICAL_LEVEL_MONSTER_PLANS[levelId]',
    '  if (rec === undefined) return null',
    "  const tier = difficulty === 'hell' ? 2 : difficulty === 'nightmare' ? 1 : 0",
    '  return {',
    '    levelId: rec.id,',
    '    levelName: rec.name,',
    '    density: rec.density[tier],',
    '    eliteMin: rec.eliteMin[tier],',
    '    eliteMax: rec.eliteMax[tier],',
    '    typeCount: rec.typeCount,',
    '    pool: rec.pool,',
    '    nightmarePool: rec.nightmarePool,',
    '    elitePool: rec.elitePool,',
    '    monsterLevel: rec.monsterLevel[tier],',
    '    wander: rec.wander,',
    '  }',
    '}',
    '',
  )
  return lines.join('\n')
}

async function main(): Promise<void> {
  const archives = mountNodeArchives(DEFAULT_NODE_MPQ_DIR)
  const table = parseTable(await archives.read(LEVELS_MEMBER))
  const rows = readLevelMonsterPlanRows(table)
  const target = resolve('src/common/world/level-monster-plans.ts')
  writeFileSync(target, renderLevelMonsterPlans(rows))
  const populated = rows.filter(r => r.density[0] > 0).length
  console.log(`wrote ${target}: ${rows.length} levels; ${populated} with MonDen > 0 on Normal`)
}

if (process.argv[1] !== undefined && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  await main()
}
