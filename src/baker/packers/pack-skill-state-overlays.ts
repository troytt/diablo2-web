/**
 * Offline packer: Diablo II 1.13c `Skills.txt` / `States.txt` overlay columns →
 * `src/common/skills/skill-state-overlays-113c.ts`.
 *
 * - Skills.txt `castoverlay` (`wCastOverlay`, +0x106) / `prgoverlay` (`wPrgOverlay`, +0x10C) / `cltstfunc`
 *   (`wCltStFunc`, +0xF2; D2Client dispatch `0x6FB52023` → table `0x6FB8E928`) for every row that names an overlay.
 * - States.txt `castoverlay` (+0x0A) / `overlay1..4` / `aura` / `nooverlays` for every row: the D2Client state-on
 *   routine `0x6FB23760` → `0x6FB22C80` reads exactly these (see kb/skills/state-castoverlay-113c.md).
 *
 * Every overlay name is validated against `Overlay.txt` (fail fast on an unknown name).
 *
 * Usage: `npx tsx src/baker/packers/pack-skill-state-overlays.ts [mpqDir]`
 */

import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { DEFAULT_NODE_MPQ_DIR, NodeMpqArchiveSource } from '../mpq-archive-source.ts'

export const SKILLS_TXT_PATH = 'data\\global\\excel\\Skills.txt'
export const STATES_TXT_PATH = 'data\\global\\excel\\States.txt'
export const OVERLAY_TXT_PATH = 'data\\global\\excel\\overlay.txt'

export interface SkillOverlayRow113c {
  readonly id: number
  readonly skill: string
  readonly castOverlay: string
  readonly prgOverlay: string
  readonly cltStFunc: number
}

export interface StateOverlayRow113c {
  readonly id: number
  readonly state: string
  readonly aura: boolean
  readonly noOverlays: boolean
  readonly castOverlay: string
  readonly overlays: readonly string[]
}

function parseTable(text: string): { header: string[]; rows: string[][] } {
  const lines = text.split(/\r?\n/)
  const header = (lines[0] ?? '').split('\t').map(h => h.trim())
  const rows = lines.slice(1).filter(l => l.trim() !== '').map(l => l.split('\t'))
  return { header, rows }
}

function col(header: readonly string[], name: string): number {
  const i = header.findIndex(h => h.toLowerCase() === name.toLowerCase())
  if (i < 0) throw new Error(`column '${name}' missing`)
  return i
}

export function extractSkillStateOverlays(
  skillsTxt: string,
  statesTxt: string,
  overlayTxt: string,
): { skills: SkillOverlayRow113c[]; states: StateOverlayRow113c[] } {
  const ov = parseTable(overlayTxt)
  const ovName = col(ov.header, 'overlay')
  const overlayNames = new Set(ov.rows.map(r => (r[ovName] ?? '').trim().toLowerCase()))
  const checkOverlay = (where: string, name: string): string => {
    if (name !== '' && !overlayNames.has(name.toLowerCase())) {
      throw new Error(`${where}: '${name}' is not an Overlay.txt row`)
    }
    return name
  }

  const sk = parseTable(skillsTxt)
  const sId = col(sk.header, 'Id')
  const sName = col(sk.header, 'skill')
  const sCast = col(sk.header, 'castoverlay')
  const sPrg = col(sk.header, 'prgoverlay')
  const sClt = col(sk.header, 'cltstfunc')
  const skills: SkillOverlayRow113c[] = []
  for (const r of sk.rows) {
    const idText = (r[sId] ?? '').trim()
    if (idText === '') continue
    const id = Number(idText)
    const skill = (r[sName] ?? '').trim()
    const castOverlay = checkOverlay(`Skills.txt #${idText} castoverlay`, (r[sCast] ?? '').trim())
    const prgOverlay = checkOverlay(`Skills.txt #${idText} prgoverlay`, (r[sPrg] ?? '').trim())
    if (castOverlay === '' && prgOverlay === '') continue
    skills.push({ id, skill, castOverlay, prgOverlay, cltStFunc: Number((r[sClt] ?? '').trim() || 0) })
  }

  const st = parseTable(statesTxt)
  const tName = col(st.header, 'state')
  const tId = col(st.header, 'id')
  const tAura = col(st.header, 'aura')
  const tNoOv = col(st.header, 'nooverlays')
  const tCast = col(st.header, 'castoverlay')
  const tOv = ['overlay1', 'overlay2', 'overlay3', 'overlay4'].map(c => col(st.header, c))
  const states: StateOverlayRow113c[] = []
  for (const r of st.rows) {
    const idText = (r[tId] ?? '').trim()
    if (idText === '') continue
    const where = `States.txt #${idText}`
    states.push({
      id: Number(idText),
      state: (r[tName] ?? '').trim(),
      aura: (r[tAura] ?? '').trim() === '1',
      noOverlays: (r[tNoOv] ?? '').trim() === '1',
      castOverlay: checkOverlay(`${where} castoverlay`, (r[tCast] ?? '').trim()),
      overlays: tOv.map(i => checkOverlay(`${where} overlay`, (r[i] ?? '').trim())).filter(n => n !== ''),
    })
  }
  return { skills, states }
}

export function renderSkillStateOverlaysModule(data: {
  skills: readonly SkillOverlayRow113c[]
  states: readonly StateOverlayRow113c[]
}): string {
  const sk = data.skills.map(r => `  ${JSON.stringify(r)},`).join('\n')
  const st = data.states.map(r => `  ${JSON.stringify(r)},`).join('\n')
  return `/**
 * AUTO-GENERATED by \`src/baker/packers/pack-skill-state-overlays.ts\` — do not edit by hand.
 *
 * Diablo II 1.13c Skills.txt \`castoverlay\` / \`prgoverlay\` / \`cltstfunc\` (rows naming an overlay) and States.txt
 * \`castoverlay\` / \`overlay1..4\` / \`aura\` / \`nooverlays\` (all rows). Every name is an Overlay.txt row.
 */

export interface SkillOverlayRow113c {
  readonly id: number
  readonly skill: string
  /** Skills.txt \`castoverlay\` (+0x106): played once on the caster at cast start. */
  readonly castOverlay: string
  /** Skills.txt \`prgoverlay\` (+0x10C): progressive / channel overlay (e.g. CltSt15 0x6FB240F0). */
  readonly prgOverlay: string
  /** Skills.txt \`cltstfunc\` (+0xF2). */
  readonly cltStFunc: number
}

export interface StateOverlayRow113c {
  readonly id: number
  readonly state: string
  /** States.txt \`aura\` (STATEMASK_AURA). */
  readonly aura: boolean
  /** States.txt \`nooverlays\`: 0x6FB22C80 returns before creating any overlay. */
  readonly noOverlays: boolean
  /** States.txt \`castoverlay\` (+0x0A): one-shot overlay on the inactive → active transition. */
  readonly castOverlay: string
  /** Non-empty States.txt \`overlay1..4\` in column order. */
  readonly overlays: readonly string[]
}

export const SKILL_OVERLAY_ROWS_113C: readonly SkillOverlayRow113c[] = Object.freeze([
${sk}
])

export const STATE_OVERLAY_ROWS_113C: readonly StateOverlayRow113c[] = Object.freeze([
${st}
])
`
}

function main(): void {
  const mpqDir = process.argv[2] ?? DEFAULT_NODE_MPQ_DIR
  const src = new NodeMpqArchiveSource(mpqDir)
  const data = extractSkillStateOverlays(
    src.readText(SKILLS_TXT_PATH),
    src.readText(STATES_TXT_PATH),
    src.readText(OVERLAY_TXT_PATH),
  )
  const here = dirname(fileURLToPath(import.meta.url))
  const outPath = join(here, '..', '..', 'common', 'skills', 'skill-state-overlays-113c.ts')
  writeFileSync(outPath, renderSkillStateOverlaysModule(data))
  console.log(`wrote ${String(data.skills.length)} skill rows + ${String(data.states.length)} state rows → ${outPath}`)
}

if (process.argv[1] !== undefined && fileURLToPath(import.meta.url) === process.argv[1]) {
  main()
}
