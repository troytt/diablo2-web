/**
 * Offline packer for the 1.13c MonStats.txt mode-missile table (`D2Common_11050`, `0x6FDA54E0`, Refs #1162).
 *
 * Usage:
 *   npx tsx src/baker/packers/pack-monster-mode-missiles.ts           # (re)write the table
 *   npx tsx src/baker/packers/pack-monster-mode-missiles.ts --check   # verify the committed table
 *
 * Reads the authoritative 1.13c `MonStats.txt` (`MissA1`, `MissA2`, `MissS1`, `MissS2`, `MissS3`, `MissS4`,
 * `MissC`, `MissSQ`) and `Missiles.txt` through the shared MPQ data registry and writes
 * `src/common/units/monster-mode-missiles-113c.ts`.
 */

import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import type { DataTable } from '../../common/items/tables.ts'
import { getSharedDataRegistry } from '../mpq-archive-source.ts'

export const MONSTER_MODE_MISSILE_COLUMNS = [
  ['A1', 'MissA1'],
  ['A2', 'MissA2'],
  ['S1', 'MissS1'],
  ['S2', 'MissS2'],
  ['S3', 'MissS3'],
  ['S4', 'MissS4'],
  ['C', 'MissC'],
  ['SQ', 'MissSQ'],
] as const

export type MonsterModeMissileKey = (typeof MONSTER_MODE_MISSILE_COLUMNS)[number][0]

export interface PackedMonsterModeMissileEntry {
  readonly hcIdx: number
  readonly id: string
  readonly missiles: Readonly<Partial<Record<MonsterModeMissileKey, string>>>
}

function isExpansionRow(row: Readonly<Record<string, string>>): boolean {
  return (row['Id'] ?? '').toLowerCase() === 'expansion'
}

function requireColumns(table: DataTable, name: string, columns: readonly string[]): void {
  for (const c of columns) {
    if (!table.columns.includes(c)) throw new Error(`${name}: missing column ${c}`)
  }
}

export function buildMonsterModeMissiles(
  monStats: DataTable,
  missiles: DataTable,
): readonly PackedMonsterModeMissileEntry[] {
  requireColumns(monStats, 'MonStats.txt', [
    'Id',
    'hcIdx',
    ...MONSTER_MODE_MISSILE_COLUMNS.map(c => c[1]),
  ])
  requireColumns(missiles, 'Missiles.txt', ['Missile', 'Id'])

  const validMissiles = new Set<string>()
  for (const r of missiles.rows) {
    const name = (r['Missile'] ?? '').trim().toLowerCase()
    const id = (r['Id'] ?? '').trim()
    if (name !== '' && id !== '') {
      validMissiles.add(name)
    }
  }

  const msRows = monStats.rows.filter(r => !isExpansionRow(r))
  const out: PackedMonsterModeMissileEntry[] = []

  for (let i = 0; i < msRows.length; i++) {
    const r = msRows[i]!
    const id = (r['Id'] ?? '').trim().toLowerCase()
    if (id === '') throw new Error(`MonStats.txt record ${i}: empty Id`)
    const hcIdx = Number(r['hcIdx'] ?? '')
    if (!Number.isInteger(hcIdx) || hcIdx !== i) {
      throw new Error(`MonStats.txt ${id}: hcIdx ${String(r['hcIdx'])} != compiled index ${i}`)
    }
    const entry: Partial<Record<MonsterModeMissileKey, string>> = {}
    let hasAny = false
    for (const [shortKey, colName] of MONSTER_MODE_MISSILE_COLUMNS) {
      const val = (r[colName] ?? '').trim().toLowerCase()
      if (val === '') continue
      if (!validMissiles.has(val)) {
        throw new Error(
          `MonStats.txt ${id} (hcIdx ${hcIdx}): ${colName}=${JSON.stringify(r[colName])} is not a valid Missiles.txt row`,
        )
      }
      entry[shortKey] = val
      hasAny = true
    }
    if (hasAny) {
      out.push({ hcIdx, id, missiles: entry })
    }
  }

  return out
}

export function renderMonsterModeMissilesModule(
  entries: readonly PackedMonsterModeMissileEntry[],
): string {
  const lines: string[] = []
  lines.push('/**')
  lines.push(' * 1.13c MonStats.txt monster mode projectiles (`D2Common_11050` at `0x6FDA54E0`, Refs #1162).')
  lines.push(' *')
  lines.push(' * GENERATED by `src/baker/packers/pack-monster-mode-missiles.ts` from `MonStats.txt` and')
  lines.push(' * `Missiles.txt`; do not edit by hand.')
  lines.push(' */')
  lines.push('')
  lines.push('export interface MonsterModeMissiles113c {')
  lines.push('  readonly A1?: string | undefined')
  lines.push('  readonly A2?: string | undefined')
  lines.push('  readonly S1?: string | undefined')
  lines.push('  readonly S2?: string | undefined')
  lines.push('  readonly S3?: string | undefined')
  lines.push('  readonly S4?: string | undefined')
  lines.push('  readonly C?: string | undefined')
  lines.push('  readonly SQ?: string | undefined')
  lines.push('}')
  lines.push('')
  lines.push('/**')
  lines.push(' * Per-hcIdx mapping of non-empty `MissA1`, `MissA2`, `MissS1..S4`, `MissC`, `MissSQ` columns')
  lines.push(' * from 1.13c `MonStats.txt`.')
  lines.push(' */')
  lines.push('export const MONSTER_MODE_MISSILES_113C: Readonly<Record<number, MonsterModeMissiles113c>> = Object.freeze({')
  for (const e of entries) {
    const props = MONSTER_MODE_MISSILE_COLUMNS.filter(([k]) => e.missiles[k] !== undefined)
      .map(([k]) => `${k}: ${JSON.stringify(e.missiles[k])}`)
      .join(', ')
    lines.push(`  ${e.hcIdx}: Object.freeze({ ${props} }), // ${e.id}`)
  }
  lines.push('})')
  lines.push('')
  lines.push('/** Per-Id (lowercase `MonStats.txt` `Id`) lookup of `MonsterModeMissiles113c`. */')
  lines.push('export const MONSTER_MODE_MISSILES_BY_ID_113C: Readonly<Record<string, MonsterModeMissiles113c>> = Object.freeze({')
  for (const e of entries) {
    lines.push(`  ${JSON.stringify(e.id)}: MONSTER_MODE_MISSILES_113C[${e.hcIdx}]!,`)
  }
  lines.push('})')
  lines.push('')
  lines.push('/**')
  lines.push(' * 1.13c `D2Common_11050` (`0x6FDA54E0`, `Monsters.cpp:1245`):')
  lines.push(' * Resolves the `Missiles.txt` key configured on `MonStats.txt` for `(classId, mode)`:')
  lines.push(' * - `4` (`MONMODE_ATTACK1` / `A1`) -> `MissA1`')
  lines.push(' * - `5` (`MONMODE_ATTACK2` / `A2`) -> `MissA2`')
  lines.push(' * - `7` (`MONMODE_CAST` / `C`) -> `MissC`')
  lines.push(' * - `8` (`MONMODE_SKILL1` / `S1`) -> `MissS1`')
  lines.push(' * - `9` (`MONMODE_SKILL2` / `S2`) -> `MissS2`')
  lines.push(' * - `10` (`MONMODE_SKILL3` / `S3`) -> `MissS3`')
  lines.push(' * - `11` (`MONMODE_SKILL4` / `S4`) -> `MissS4`')
  lines.push(' * - `14` (`MONMODE_SEQUENCE` / `SQ`) -> `MissSQ`')
  lines.push(' */')
  lines.push('export function getMonsterModeMissile113c(classId: number, mode: number): string | undefined {')
  lines.push('  const entry = MONSTER_MODE_MISSILES_113C[classId]')
  lines.push('  if (!entry) return undefined')
  lines.push('  switch (mode) {')
  lines.push('    case 4:')
  lines.push('      return entry.A1')
  lines.push('    case 5:')
  lines.push('      return entry.A2')
  lines.push('    case 7:')
  lines.push('      return entry.C')
  lines.push('    case 8:')
  lines.push('      return entry.S1')
  lines.push('    case 9:')
  lines.push('      return entry.S2')
  lines.push('    case 10:')
  lines.push('      return entry.S3')
  lines.push('    case 11:')
  lines.push('      return entry.S4')
  lines.push('    case 14:')
  lines.push('      return entry.SQ')
  lines.push('    default:')
  lines.push('      return undefined')
  lines.push('  }')
  lines.push('}')
  lines.push('')
  lines.push('export function getMonsterModeMissileById113c(monId: string, mode: number): string | undefined {')
  lines.push('  const entry = MONSTER_MODE_MISSILES_BY_ID_113C[monId.trim().toLowerCase()]')
  lines.push('  if (!entry) return undefined')
  lines.push('  switch (mode) {')
  lines.push('    case 4:')
  lines.push('      return entry.A1')
  lines.push('    case 5:')
  lines.push('      return entry.A2')
  lines.push('    case 7:')
  lines.push('      return entry.C')
  lines.push('    case 8:')
  lines.push('      return entry.S1')
  lines.push('    case 9:')
  lines.push('      return entry.S2')
  lines.push('    case 10:')
  lines.push('      return entry.S3')
  lines.push('    case 11:')
  lines.push('      return entry.S4')
  lines.push('    case 14:')
  lines.push('      return entry.SQ')
  lines.push('    default:')
  lines.push('      return undefined')
  lines.push('  }')
  lines.push('}')
  lines.push('')
  return lines.join('\n')
}

export const MONSTER_MODE_MISSILES_MODULE = join('src', 'common', 'units', 'monster-mode-missiles-113c.ts')

export async function packMonsterModeMissiles(rootDir: string = process.cwd(), check = false): Promise<string> {
  const reg = await getSharedDataRegistry()
  const text = renderMonsterModeMissilesModule(
    buildMonsterModeMissiles(reg.monStatsTable, reg.missilesTable),
  )
  const target = join(rootDir, MONSTER_MODE_MISSILES_MODULE)
  if (check) {
    const current = readFileSync(target, 'utf-8')
    if (current !== text) throw new Error(`${MONSTER_MODE_MISSILES_MODULE} is stale; re-run the packer`)
  } else {
    writeFileSync(target, text)
  }
  return text
}

if (process.argv[1] && process.argv[1].endsWith('pack-monster-mode-missiles.ts')) {
  const check = process.argv.includes('--check')
  packMonsterModeMissiles(process.cwd(), check)
    .then(() =>
      console.log(
        check ? `${MONSTER_MODE_MISSILES_MODULE} is up to date` : `wrote ${MONSTER_MODE_MISSILES_MODULE}`,
      ),
    )
    .catch(err => {
      console.error(err)
      process.exit(1)
    })
}
