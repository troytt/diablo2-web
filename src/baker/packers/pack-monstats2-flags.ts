/**
 * Offline packer: Diablo II 1.13c `monstats.bin` + `monstats2.bin` → `src/common/units/monstats2-flags-data.ts`.
 *
 * The client resolves a monster's MonStats2 flag bit exactly like D2Client `0x6FAB1510(eax=classId, edx=flagIndex)`:
 * - MonStats record = `sgptDataTables+0xA78` (stride `0x1A8`, count `+0xA80`); `classId` out of range → 0.
 * - `wMonStatsEx` = int16 at record `+0x18` (`movsx`, `0x6fab1531`); MonStats2 record = `sgptDataTables+0xA90`
 *   (stride `0x134`, count `+0xA98`); index out of range → 0.
 * - flag = `byte[record + 0x04 + (flagIndex >> 3)] & gdwBitMasks[flagIndex & 7]` (`0x6fab155d`; Fog `gdwBitMasks`
 *   = `1 << n`), i.e. bit `flagIndex` of the little-endian dword `D2MonStats2Txt.dwFlags` at `+0x04`
 *   (flag indices: D2MOO `MonsterTbls.h:224-269`).
 *
 * The table stores that dword per MonStats `hcIdx` (bin record index), or `null` when the record has no MonStats2
 * row (`wMonStatsEx` out of range). Every flag is read from the compiled bins — the txt files are not consulted, so
 * their `Expansion` divider rows cannot shift indices.
 *
 * Usage: `npx tsx src/baker/packers/pack-monstats2-flags.ts [mpqDir]`
 */

import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { DEFAULT_NODE_MPQ_DIR, NodeMpqArchiveSource } from '../mpq-archive-source.ts'

export const MONSTATS_BIN_PATH = 'data\\global\\excel\\monstats.bin'
export const MONSTATS2_BIN_PATH = 'data\\global\\excel\\monstats2.bin'
/** `sizeof(D2MonStatsTxt)` — stride used at D2Client `0x6fab152b` (`imul eax, eax, 0x1a8`). */
export const MONSTATS_BIN_RECORD_SIZE = 0x1a8
/** `sizeof(D2MonStats2Txt)` — stride used at D2Client `0x6fab1548` (`imul eax, eax, 0x134`). */
export const MONSTATS2_BIN_RECORD_SIZE = 0x134
/** `D2MonStatsTxt.wMonStatsEx` (D2Client `0x6fab1531`). */
const MONSTATS_WMONSTATSEX_OFFSET = 0x18
/** `D2MonStats2Txt.dwFlags` (D2Client `0x6fab155d`: `[record + 0x04 + (flagIndex >> 3)]`). */
const MONSTATS2_FLAGS_OFFSET = 0x04

export interface MonStats2FlagsSource {
  readBytes(mpqRelativePath: string): Uint8Array
}

function readCountedRecords(bin: Uint8Array, recordSize: number, label: string): DataView {
  if (bin.byteLength < 4) throw new Error(`${label} too short`)
  const dv = new DataView(bin.buffer, bin.byteOffset, bin.byteLength)
  const count = dv.getUint32(0, true)
  if (4 + count * recordSize !== bin.byteLength) {
    throw new Error(
      `${label} size ${String(bin.byteLength)} != 4 + ${String(count)} * 0x${recordSize.toString(16)}`,
    )
  }
  return dv
}

/** `D2MonStats2Txt.dwFlags` per MonStats `hcIdx`, `null` when `wMonStatsEx` has no MonStats2 record. */
export function extractMonStats2FlagsByHcIdx(src: MonStats2FlagsSource): (number | null)[] {
  const ms = readCountedRecords(src.readBytes(MONSTATS_BIN_PATH), MONSTATS_BIN_RECORD_SIZE, 'monstats.bin')
  const ms2 = readCountedRecords(src.readBytes(MONSTATS2_BIN_PATH), MONSTATS2_BIN_RECORD_SIZE, 'monstats2.bin')
  const msCount = ms.getUint32(0, true)
  const ms2Count = ms2.getUint32(0, true)
  const out: (number | null)[] = []
  for (let hcIdx = 0; hcIdx < msCount; hcIdx++) {
    const ex = ms.getInt16(4 + hcIdx * MONSTATS_BIN_RECORD_SIZE + MONSTATS_WMONSTATSEX_OFFSET, true)
    if (ex < 0 || ex >= ms2Count) {
      out.push(null)
      continue
    }
    out.push(ms2.getUint32(4 + ex * MONSTATS2_BIN_RECORD_SIZE + MONSTATS2_FLAGS_OFFSET, true))
  }
  return out
}

export function renderMonStats2FlagsModule(flags: readonly (number | null)[]): string {
  const rows: string[] = []
  for (let i = 0; i < flags.length; i += 8) {
    const chunk = flags.slice(i, i + 8).map(f => (f === null ? 'null' : `0x${f.toString(16)}`))
    rows.push(`  ${chunk.join(', ')}, // ${String(i)}`)
  }
  return `/**
 * AUTO-GENERATED by \`src/baker/packers/pack-monstats2-flags.ts\` — do not edit by hand.
 *
 * Diablo II 1.13c \`D2MonStats2Txt.dwFlags\` (\`monstats2.bin\` record \`+0x04\`) for each MonStats \`hcIdx\`
 * (\`monstats.bin\` record index, ${String(flags.length)} records), resolved through \`wMonStatsEx\`; \`null\` = no MonStats2
 * record. Lookup semantics: D2Client \`0x6FAB1510\` (see \`monstats2-flags.ts\`).
 */
export const MONSTATS2_FLAGS_BY_HCIDX: readonly (number | null)[] = Object.freeze([
${rows.join('\n')}
])
`
}

function main(): void {
  const mpqDir = process.argv[2] ?? DEFAULT_NODE_MPQ_DIR
  const flags = extractMonStats2FlagsByHcIdx(new NodeMpqArchiveSource(mpqDir))
  const here = dirname(fileURLToPath(import.meta.url))
  const outPath = join(here, '..', '..', 'common', 'units', 'monstats2-flags-data.ts')
  writeFileSync(outPath, renderMonStats2FlagsModule(flags))
  console.log(`wrote ${String(flags.length)} MonStats2 flag dwords → ${outPath}`)
}

if (process.argv[1] !== undefined && fileURLToPath(import.meta.url) === process.argv[1]) {
  main()
}
