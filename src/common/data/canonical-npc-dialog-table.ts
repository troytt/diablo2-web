/**
 * Resolves the canonical `.tbl` key (`A1Q1InitAkara`, `AkaraIntroGossip1`, etc.)
 * for a raw 16-bit D2GS `S2C 0x27 NPCInfo` / `C2S 0x31 QuestMessage` string index.
 */
export function resolveNpcMsgIdTblKey(msgId: number): string | undefined {
  return CANONICAL_NPC_MSG_ID_TO_TBL_KEY[msgId]
}

/**
 * Resolves the canonical quest title `.tbl` key (`qstsa1q1`..`qstsa5q6`) from
 * `D2Client.dll 0x6fb91400` for a quest dialogue `wStringId`.
 */
export function resolveQuestTitleKeyForMsgId(msgId: number): string | undefined {
  return CANONICAL_QUEST_SPEECH_MSG_TO_TITLE_KEY[msgId]
}

/**
 * Returns true if `msgId` is an NPC Intro/Greeting message (not a quest message).
 * In 1.13c, `S2C 0x27` sends NPC Intro messages in `nMenu == 0` on first visit;
 * the Talk submenu already renders a dedicated `talk_intro` (`介紹` / `Introduction`) option,
 * so pure intro messages should not be duplicated as generic `Quest #N` items.
 */
export function isNpcIntroMessageId(msgId: number): boolean {
  if (CANONICAL_QUEST_SPEECH_MSG_TO_TITLE_KEY[msgId]) return false
  const key = CANONICAL_NPC_MSG_ID_TO_TBL_KEY[msgId]
  if (!key) return false
  return /Intro|Gossip|Greet/i.test(key) && !/^A[1-5]Q[1-6]/i.test(key)
}

/**
 * Class-variant infixes that 1.13c `string.tbl` / `expansionstring.tbl` use for per-character-class
 * greeting variants (`AkaraIntroGossip1` vs `AkaraIntroSorGossip1`, `NihlathakAct5IntroAssGossip1`,
 * `QualKehkAct5IntroDruGossip1`, ...). D2Game resolves the variant server-side per player class,
 * so reverse lookups normalize the infix away.
 */
const NPC_INTRO_CLASS_VARIANTS = ['Sor', 'Pal', 'Ama', 'Nec', 'Bar', 'Ass', 'Dru'] as const

let introTblKeyToMsgIdCache: Map<string, number> | null = null

function getIntroTblKeyToMsgIdMap(): Map<string, number> {
  if (introTblKeyToMsgIdCache === null) {
    const map = new Map<string, number>()
    for (const msgIdStr of Object.keys(CANONICAL_NPC_MSG_ID_TO_TBL_KEY)) {
      const msgId = Number(msgIdStr)
      const key = CANONICAL_NPC_MSG_ID_TO_TBL_KEY[msgId]!
      if (!isNpcIntroMessageId(msgId)) continue
      let normalized = key
      for (const variant of NPC_INTRO_CLASS_VARIANTS) {
        normalized = normalized.split(`Intro${variant}`).join('Intro')
      }
      if (!map.has(normalized)) map.set(normalized, msgId)
    }
    introTblKeyToMsgIdCache = map
  }
  return introTblKeyToMsgIdCache
}

/**
 * Resolves the canonical `C2S 0x31 QuestMessage` msgId for an NPC Intro/Greeting `.tbl` key
 * (e.g. `'WarrivAct1IntroGossip1'` -> `1`, `'AkaraIntroGossip1'` -> `11`). Class-variant
 * infixes are normalized so the generic `NPC_CANONICAL_INTRO_KEYS` entries resolve against
 * the single indexed variant. Returns `undefined` when the NPC has no indexed intro msgId.
 */
export function resolveNpcIntroMsgIdByTblKey(tblKey: string): number | undefined {
  const map = getIntroTblKeyToMsgIdMap()
  const direct = map.get(tblKey)
  if (direct !== undefined) return direct
  for (const [idStr, key] of Object.entries(CANONICAL_NPC_MSG_ID_TO_TBL_KEY)) {
    if (key === tblKey) return Number(idStr)
  }
  return undefined
}
