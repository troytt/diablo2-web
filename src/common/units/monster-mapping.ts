/**
 * Resolve the visual token and weapon class for a given monster ID.
 */
export function resolveMonsterArtSpec(id: string): MonsterArtSpec | null {
  const lower = id.toLowerCase()
  const direct = MONSTER_ART_MAP[lower]
  if (direct && direct.token.trim() !== '') {
    return direct
  }
  const base = lower.replace(/\d+$/, '')
  if (base !== lower) {
    const baseSpec = MONSTER_ART_MAP[base]
    if (baseSpec && baseSpec.token.trim() !== '') {
      return baseSpec
    }
  }
  return null
}

