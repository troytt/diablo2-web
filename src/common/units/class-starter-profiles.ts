function buildSocketableStats(code: string): readonly { text: string; color: 'white' }[] {
  const info = getSocketableInfo(code)
  if (!info) return []
  return [
    { text: '可镶嵌进有凹槽的装备', color: 'white' },
    { text: `武器: ${info.weaponsZh}`, color: 'white' },
    { text: `防具: ${info.armorZh}`, color: 'white' },
    { text: `头盔: ${info.helmsZh}`, color: 'white' },
    { text: `盾牌: ${info.shieldsZh}`, color: 'white' },
  ]
}

