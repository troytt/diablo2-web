export interface OverheadBubbleLayout extends OverheadSpeechRect113c {
  readonly boxX: number
  readonly boxY: number
  readonly boxW: number
  readonly boxH: number
  readonly rect: OverheadSpeechRect113c
  readonly lines: readonly WrappedChatLine113c[]
  readonly lineWidths: readonly number[]
}

/**
 * Computes the initial bounding box and wrapped text lines for a unit overhead speech bubble
 * per `D2Client.dll` `0x6fb2ca40` (`MSG_DrawUnitOverheadBubble`).
 */
export function computeOverheadBubbleLayout113c(
  text: string,
  unitScreenX: number,
  unitScreenY: number,
  measureFn: (s: string) => number,
  baseColor = 0,
): OverheadBubbleLayout {
  const trimmed = text.trim()
  const lines = trimmed
    ? wrapChatText113c(trimmed, measureFn, OVERHEAD_BUBBLE_MAX_WRAP_WIDTH_PX, baseColor, 8)
    : []
  const lineWidths = lines.map((line) => line.width)
  const maxLineWidth = lineWidths.length > 0 ? Math.max(1, ...lineWidths) : 0
  const width = Math.max(24, maxLineWidth + OVERHEAD_BUBBLE_PADDING_X)
  const height = lines.length * OVERHEAD_BUBBLE_LINE_HEIGHT_PX + OVERHEAD_BUBBLE_PADDING_Y

  const left = Math.round(unitScreenX - width / 2)
  const bottom = Math.round(unitScreenY - OVERHEAD_BUBBLE_ANCHOR_OFFSET_Y)
  const top = bottom - height
  const right = left + width
  const rect: OverheadSpeechRect113c = {
    x: left,
    y: top,
    w: width,
    h: height,
    width,
    height,
    left,
    top,
    right,
    bottom,
  }

  return {
    ...rect,
    boxX: left,
    boxY: top,
    boxW: width,
    boxH: height,
    rect,
    lines,
    lineWidths,
  }
}

function normalizeOverheadRect(
  input: Partial<OverheadSpeechRect113c> & {
    x?: number
    y?: number
    w?: number
    h?: number
    width?: number
    height?: number
    left?: number
    top?: number
  },
): OverheadSpeechRect113c {
  const x = input.x ?? input.left ?? 0
  const y = input.y ?? input.top ?? 0
  const w = input.width ?? input.w ?? 0
  const h = input.height ?? input.h ?? 0
  return {
    x,
    y,
    w,
    h,
    width: w,
    height: h,
    left: x,
    top: y,
    right: x + w,
    bottom: y + h,
  }
}

function rectsOverlap(a: OverheadSpeechRect113c, b: OverheadSpeechRect113c): boolean {
  return a.left < b.right && a.right > b.left && a.top < b.bottom && a.bottom > b.top
}

/**
 * Adjusts `candidate` vertically to avoid overlapping up to 16 previously placed overhead
 * speech bubble rectangles (`D2Client.dll` `0x6fb2af20` `MSG_AvoidOverheadRectOverlap`),
 * then registers the adjusted rectangle in `placedRects`.
 */
export function resolveOverheadBubbleOverlap113c(
  candidate: {
    x?: number
    y?: number
    w?: number
    h?: number
    width?: number
    height?: number
    left?: number
    top?: number
    right?: number
    bottom?: number
  },
  placedRects: Array<{
    x?: number
    y?: number
    w?: number
    h?: number
    width?: number
    height?: number
    left?: number
    top?: number
    right?: number
    bottom?: number
  }>,
): OverheadSpeechRect113c {
  const cur = normalizeOverheadRect(candidate)
  const tracked = placedRects.slice(0, OVERHEAD_BUBBLE_MAX_TRACKED_RECTS).map(normalizeOverheadRect)
  let guard = 0
  while (guard < OVERHEAD_BUBBLE_MAX_TRACKED_RECTS) {
    const colliding = tracked.find((other) => rectsOverlap(cur, other))
    if (!colliding) break
    cur.bottom = colliding.top - 2
    cur.top = cur.bottom - cur.height
    cur.y = cur.top
    guard++
  }
  if (placedRects.length < OVERHEAD_BUBBLE_MAX_TRACKED_RECTS) {
    placedRects.push({ ...cur })
  }
  return cur
}
