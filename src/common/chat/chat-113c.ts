/**
 * Formats a `0x5A` event `0x07` party/hostility/corpse-loot relation message
 * per `D2Client.dll` `0x6fb2cfc0` (`MSG_FormatPartyEventMessage`, jump table `0x6fb2d1d4`).
 */
export function formatPartyRelationEvent0x5A(
  subType: number,
  playerName: string,
  lang: 'ENG' | 'CHI' = 'CHI',
): string {
  const name = playerName || 'Player'
  switch (subType) {
    case 1:
      // 0x277A = patchstring#106: "%s permits you to loot his corpse."
      return formatTblPrintf(resolveChatTblIndex(0x277a, lang) || '%s permits you to loot his corpse.', name)
    case 2:
      // 0x277B = patchstring#107: "%s permits you to loot her corpse."
      return formatTblPrintf(resolveChatTblIndex(0x277b, lang) || '%s permits you to loot her corpse.', name)
    case 3:
      // 0x0FBA = string#4026: " has expressed hostility towards you."
      return `${name}${resolveChatTblIndex(0x0fba, lang) || ' has expressed hostility towards you.'}`
    case 4:
      // 0x0FBB = string#4027: " is no longer hostile towards you."
      return `${name}${resolveChatTblIndex(0x0fbb, lang) || ' is no longer hostile towards you.'}`
    case 5:
      // 0x0FBC = string#4028: " invites you to ally against the forces of evil."
      return `${name}${resolveChatTblIndex(0x0fbc, lang) || ' invites you to ally against the forces of evil.'}`
    case 6:
      // 0x0FBD = string#4029: " has cancelled the party invite."
      return `${name}${resolveChatTblIndex(0x0fbd, lang) || ' has cancelled the party invite.'}`
    case 7:
      // 0x0FBE = string#4030: " has joined your party to fight the forces of evil."
      return `${name}${resolveChatTblIndex(0x0fbe, lang) || ' has joined your party to fight the forces of evil.'}`
    case 8:
      // 0x0FBF = string#4031: "You are now allied with "
      return `${resolveChatTblIndex(0x0fbf, lang) || 'You are now allied with '}${name}`
    case 9:
      // 0x0FC0 = string#4032: " has left your party."
      return `${name}${resolveChatTblIndex(0x0fc0, lang) || ' has left your party.'}`
    case 10:
      // 0x277C = patchstring#108: "%s no longer allows you to access his corpse."
      return formatTblPrintf(
        resolveChatTblIndex(0x277c, lang) || '%s no longer allows you to access his corpse.',
        name,
      )
    case 11:
      // 0x277D = patchstring#109: "%s no longer allows you to access her corpse."
      return formatTblPrintf(
        resolveChatTblIndex(0x277d, lang) || '%s no longer allows you to access her corpse.',
        name,
      )
    default:
      return ''
  }
}

/**
 * Formats an incoming `S2C 0x5A` event packet per `D2Client.dll` `0x6fb2e200`
 * (`MSG_Packet0x5A_EventMessage`, jump table `0x6fb2e68c`).
 */
export function formatEventPacket0x5A(
  input: Packet0x5AFormatInput,
  lang: 'ENG' | 'CHI' = 'CHI',
): FormattedEvent0x5A {
  const { eventType, resolvedPlayerName, resolvedKillerName } = input
  const color = input.color ?? 0
  const arg = input.arg ?? 0
  const subType = input.subType ?? 0
  const name1 = input.name1 ?? ''
  const name2 = input.name2 ?? ''

  switch (eventType) {
    case 0x00: {
      // Dropped due to timeout (0x0E37 = string#3639, forced color 4 = gold)
      const suffix = resolveChatTblIndex(0x0e37, lang) || ' dropped due to timeout.'
      return { text: `${name1}${suffix}`, color: 4 }
    }
    case 0x01: {
      // Dropped due to errors (0x0E38 = string#3640, forced color 4 = gold)
      const suffix = resolveChatTblIndex(0x0e38, lang) || ' dropped due to errors.'
      return { text: `${name1}${suffix}`, color: 4 }
    }
    case 0x02: {
      // Joined our world (0x0E3B = string#3643 with account, 0x0E39 = string#3641 without account, color 4)
      if (name2) {
        const tmpl =
          resolveChatTblIndex(0x0e3b, lang) || "%s(%s) joined our world. Diablo's minions grow stronger."
        return { text: formatTblPrintf(tmpl, name1, name2), color: 4 }
      }
      const tmpl = resolveChatTblIndex(0x0e39, lang) || "%s joined our world. Diablo's minions grow stronger."
      return { text: formatTblPrintf(tmpl, name1), color: 4 }
    }
    case 0x03: {
      // Left our world (0x0E3C = string#3644 with account, 0x0E3A = string#3642 without account, color 4)
      if (name2) {
        const tmpl = resolveChatTblIndex(0x0e3c, lang) || "%s(%s) left our world. Diablo's minions weaken."
        return { text: formatTblPrintf(tmpl, name1, name2), color: 4 }
      }
      const tmpl = resolveChatTblIndex(0x0e3a, lang) || "%s left our world. Diablo's minions weaken."
      return { text: formatTblPrintf(tmpl, name1), color: 4 }
    }
    case 0x04: {
      // Is not in the game (0x0E3D = string#3645)
      const suffix = resolveChatTblIndex(0x0e3d, lang) || ' is not in the game.'
      return { text: `${name1}${suffix}`, color }
    }
    case 0x05: {
      // Is not logged in (0x0E3E = string#3646)
      const suffix = resolveChatTblIndex(0x0e3e, lang) || ' is not logged in.'
      return { text: `${name1}${suffix}`, color }
    }
    case 0x06: {
      // Slain by (0x0E3F = string#3647 / 0x0E41 = string#3649)
      const killer = resolvedKillerName || name2
      if (killer) {
        const mid = resolveChatTblIndex(0x0e3f, lang) || ' was slain by '
        return { text: `${name1}${mid}${killer}`, color }
      }
      const suffix = resolveChatTblIndex(0x0e41, lang) || ' was slain.'
      return { text: `${name1}${suffix}`, color }
    }
    case 0x07: {
      // Party / hostility / corpse loot relation change (0x6fb2cfc0)
      const targetName = resolvedPlayerName || name1 || (arg ? `Player#${arg}` : 'Player')
      const text = formatPartyRelationEvent0x5A(subType, targetName, lang)
      return { text, color }
    }
    case 0x08: {
      // Player is busy (0x0FCC = string#4044)
      const suffix = resolveChatTblIndex(0x0fcc, lang) || ' is busy'
      return { text: `${name1}${suffix}`, color }
    }
    case 0x09: {
      // Must wait a short time to trade (0x0FCF = string#4047)
      const text =
        resolveChatTblIndex(0x0fcf, lang) || 'You must wait a short time to trade with that player.'
      return { text, color }
    }
    case 0x0a: {
      // Item has been in your box (0x1026 = string#4134 / 0x1027 = string#4135)
      if (name1) {
        const suffix = resolveChatTblIndex(0x1026, lang) || ' has been in your box.'
        return { text: `${name1}${suffix}`, color }
      }
      const text = resolveChatTblIndex(0x1027, lang) || 'An item has been in your box.'
      return { text, color }
    }
    case 0x0d: {
      // Player is not listening to you (0x0E44 = string#3652)
      const suffix = resolveChatTblIndex(0x0e44, lang) || ' is not listening to you.'
      return { text: `${name1}${suffix}`, color }
    }
    case 0x0e: {
      return { text: name1 || name2, color }
    }
    case 0x0f: {
      // Realm going down in %d minutes (0x0E43 = string#3651)
      const tmpl = resolveChatTblIndex(0x0e43, lang) || 'Realm is going down in %d minutes.'
      return { text: formatTblPrintf(tmpl, arg), color }
    }
    case 0x10: {
      // Must wait a short time to declare hostility (0x2A38 = patchstring#808)
      const text =
        resolveChatTblIndex(0x2a38, lang) ||
        'You must wait a short time to declare hostility with that player.'
      return { text, color }
    }
    case 0x11: {
      // %d Stones of Jordan Sold to Merchants (0x2AFC = patchstring#1004, color 4)
      const tmpl = resolveChatTblIndex(0x2afc, lang) || '%d Stones of Jordan Sold to Merchants'
      return { text: formatTblPrintf(tmpl, arg), color: color || 4 }
    }
    case 0x12: {
      // Diablo Walks the Earth (0x2AFD = patchstring#1005, color 4)
      const text = resolveChatTblIndex(0x2afd, lang) || 'Diablo Walks the Earth'
      return { text, color: color || 4 }
    }
    default: {
      const fallback = [name1, name2].filter(Boolean).join(' ')
      return { text: fallback || `Event 0x${eventType.toString(16)}`, color }
    }
  }
}

// ─── 1.13c In-Game Chat Input Command Parser ─────────────────────────────────

export type ParsedChatInput =
  | { readonly kind: 'noop' }
  | { readonly kind: 'say'; readonly text: string }
  | { readonly kind: 'overhead'; readonly text: string }
  | { readonly kind: 'whisper'; readonly target: string; readonly text: string }
  | {
      readonly kind: 'bncs_command'
      readonly command: string
      readonly isAnnounce?: boolean | undefined
    }
  | { readonly kind: 'local_clear' }
  | { readonly kind: 'local_fps' }
  | {
      readonly kind: 'local_players'
      readonly count: number | null
      readonly valid: boolean
      readonly rawCount?: number
    }
  | {
      readonly kind: 'local_error'
      readonly errorKey: 'whisperUsage' | 'noReplyTarget' | 'announceUsage'
    }

/**
 * Parses raw text entered in the 1.13c in-game chat bar (`Enter` key) per
 * `D2Client.dll` `0x6fb207f0` & `0x6fb1ec30` (`UI\chat.cpp`) and `D2Multi.dll` `0x6f9db090`:
 * - `!text` -> `{ kind: 'overhead', text }` (`C2S 0x14` OverheadChat; `!` alone clears overhead speech)
 * - `%<target> <msg>`, `/w <target> <msg>`, `/whisper <target> <msg>`, `/msg <target> <msg>`, `/m <target> <msg>`
 *   -> `{ kind: 'whisper', target, text }` (`C2S 0x15` type `0x02`)
 * - `/r <msg>`, `/reply <msg>` -> whispers `lastWhisperTarget`
 * - `/clear` -> `{ kind: 'local_clear' }`
 * - `/fps`, `/framerate` -> `{ kind: 'local_fps' }`
 * - `/players [N]` or `players N` -> `{ kind: 'local_players', ... }`
 * - `/ann <msg>`, `/announce <msg>`, and other `/` Battle.net slash commands (`0x6fb2084d` `w_flag = 3`
 *   -> `0x6fb20c27` `pBnetCallbacks->vtable[+0x14]` -> `Bnclient.dll` `0x6ff2c400` `SID_CHATCOMMAND 0x0E`)
 *   -> `{ kind: 'bncs_command', command }`
 * - Anything else -> `{ kind: 'say', text }` (`C2S 0x15` type `0x01`)
 */
export function parseInGameChatInput(
  rawInput: string,
  lastWhisperTarget?: string | null,
): ParsedChatInput {
  const trimmed = rawInput.trim()
  if (!trimmed) {
    return { kind: 'noop' }
  }

  // 1. Overhead speech bubble (`!text`, `0x6fb2dc00`)
  if (trimmed.startsWith('!')) {
    const overheadText = trimmed.slice(1).trim().slice(0, CHAT_INPUT_MAX_CHARS)
    return { kind: 'overhead', text: overheadText }
  }

  // 2. Whisper shorthand `%target message`
  if (trimmed.startsWith('%')) {
    const rest = trimmed.slice(1).trim()
    const spaceIdx = rest.search(/\s/)
    if (spaceIdx <= 0) {
      return { kind: 'local_error', errorKey: 'whisperUsage' }
    }
    const target = rest.slice(0, spaceIdx).trim()
    const msg = rest.slice(spaceIdx + 1).trim().slice(0, CHAT_INPUT_MAX_CHARS)
    if (!target || !msg) {
      return { kind: 'local_error', errorKey: 'whisperUsage' }
    }
    return { kind: 'whisper', target, text: msg }
  }

  // 3. Slash commands (`0x6fb2084d`: `w_flag = 3`)
  if (trimmed.startsWith('/')) {
    // /clear -> clear active top-left chat stream
    if (/^\/clear$/i.test(trimmed)) {
      return { kind: 'local_clear' }
    }

    // /fps or /framerate (`0x6fb20b70`) -> toggle FPS display
    if (/^\/(?:fps|framerate)$/i.test(trimmed)) {
      return { kind: 'local_fps' }
    }

    // /players [N], /players set N, or /players:N
    const playersMatch = trimmed.match(/^\/players(?:\s+(?:set\s+)?|\s*:\s*)(-?\d+)$|^\/players$/i)
    if (playersMatch) {
      if (playersMatch[1] === undefined) {
        return { kind: 'local_players', count: null, valid: true }
      }
      const n = parseInt(playersMatch[1], 10)
      if (n >= 1 && n <= 8) {
        return { kind: 'local_players', count: n, valid: true }
      }
      return { kind: 'local_players', count: null, valid: false, rawCount: n }
    }

    // /r <msg> or /reply <msg>
    const replyMatch = trimmed.match(/^\/(?:r|reply)(?:\s+([\s\S]*))?$/i)
    if (replyMatch) {
      if (!lastWhisperTarget) {
        return { kind: 'local_error', errorKey: 'noReplyTarget' }
      }
      const msg = (replyMatch[1] ?? '').trim().slice(0, CHAT_INPUT_MAX_CHARS)
      if (!msg) {
        return { kind: 'local_error', errorKey: 'whisperUsage' }
      }
      return { kind: 'whisper', target: lastWhisperTarget, text: msg }
    }

    // /w <target> <msg>, /whisper <target> <msg>, /msg <target> <msg>, /m <target> <msg> (`0x6fb20500`)
    const whisperCmdMatch = trimmed.match(/^\/(?:w|whisper|msg|m)(?:\s+(\S+)(?:\s+([\s\S]*))?)?$/i)
    if (whisperCmdMatch) {
      const target = (whisperCmdMatch[1] ?? '').trim()
      const msg = (whisperCmdMatch[2] ?? '').trim().slice(0, CHAT_INPUT_MAX_CHARS)
      if (!target || !msg) {
        return { kind: 'local_error', errorKey: 'whisperUsage' }
      }
      return { kind: 'whisper', target, text: msg }
    }

    // /ann <msg> or /announce <msg> (BNCS / PvPGN server-wide global announcement via SID_CHATCOMMAND 0x0E)
    const announceMatch = trimmed.match(/^\/(?:ann|announce)(?:\s+([\s\S]*))?$/i)
    if (announceMatch) {
      const msg = (announceMatch[1] ?? '').trim()
      if (!msg) {
        return { kind: 'local_error', errorKey: 'announceUsage' }
      }
      return {
        kind: 'bncs_command',
        command: trimmed.slice(0, CHAT_INPUT_MAX_CHARS),
        isAnnounce: true,
      }
    }

    // All other '/' commands (`0x6fb20c1f..0x6fb20c37`: /whoami, /whois, /whereis, /friends, /f, /time, /channel, etc.)
    // are forwarded to BNCS via `pBnetCallbacks->vtable[+0x14]` -> `SID_CHATCOMMAND (0x0E)`.
    return {
      kind: 'bncs_command',
      command: trimmed.slice(0, CHAT_INPUT_MAX_CHARS),
    }
  }

  // Also support bare "players N" (1.13c single-player parity)
  const barePlayersMatch = trimmed.match(/^players(?:\s+(?:set\s+)?|\s*:\s*)(-?\d+)$/i)
  if (barePlayersMatch && barePlayersMatch[1] !== undefined) {
    const n = parseInt(barePlayersMatch[1], 10)
    if (n >= 1 && n <= 8) {
      return { kind: 'local_players', count: n, valid: true }
    }
    return { kind: 'local_players', count: null, valid: false, rawCount: n }
  }

  return { kind: 'say', text: trimmed.slice(0, CHAT_INPUT_MAX_CHARS) }
}

/**
 * Extracts a valid `/players N` (`1..8`) count from an in-game chat command string,
 * or returns `null` if the string is not a valid `/players 1..8` command.
 */
export function extractPlayersCommandCount(rawInput: string): number | null {
  const parsed = parseInGameChatInput(rawInput)
  if (parsed.kind === 'local_players' && parsed.valid && parsed.count !== null) {
    return parsed.count
  }
  return null
}

