/**
 * Formats an incoming `S2C 0x26` chat packet per `D2Client.dll` `0x6fb2dee0` (`MSG_Packet0x26_Chat`).
 *
 * - `0x01` (Normal chat): `<nick><string#4048 (0x0FD0)><msg>` (`": "` in ENG, `"："` in CHI)
 * - `0x02` (Whisper from): `<nick><string#3654 (0x0E46)><msg>` (`" whispers: "` in ENG, `"耳語："` in CHI)
 * - `0x04` (System message): `<msg>`
 * - `0x05` (Overhead speech `!text`): sets unit overhead text only (does not append to chat log)
 * - `0x06` (Whisper to echo): `sprintf(string#3658 (0x0E4A), nick, msg)`
 */
export function formatChatPacket0x26(
  input: Packet0x26FormatInput,
  lang: 'ENG' | 'CHI' = 'CHI',
): FormattedChat0x26 {
  const { chatType } = input
  const color = input.color ?? 0
  const senderName = (input.senderName ?? input.charName ?? '').trim()
  const accountName = (input.accountName ?? '').trim()
  const message = unwrapStormWin1252GbkString(input.message ?? input.text ?? '')
  switch (chatType) {
    case 0x01: {
      const colon = resolveChatTblIndex(0x0fd0, lang) || (lang === 'CHI' ? '：' : ': ')
      return {
        kind: 'say',
        text: senderName ? `${senderName}${colon}${message}` : message,
        color,
        sender: senderName,
        rawMessage: message,
      }
    }
    case 0x02: {
      const displaySender = accountName ? `${senderName} (${accountName})` : senderName
      const whisperInfix =
        resolveChatTblIndex(0x0e46, lang) || (lang === 'CHI' ? '耳語：' : ' whispers: ')
      return {
        kind: 'whisper',
        text: displaySender ? `${displaySender}${whisperInfix}${message}` : message,
        color,
        sender: senderName,
        rawMessage: message,
      }
    }
    case 0x05: {
      return {
        kind: 'overhead',
        text: message,
        color,
        sender: senderName,
        rawMessage: message,
      }
    }
    case 0x06: {
      const tmpl =
        resolveChatTblIndex(0x0e4a, lang) ||
        (lang === 'CHI' ? 'ÿc0你的耳語對像是ÿc1%sÿc0：%s' : 'ÿc0You whispered to ÿc1%sÿc0: %s')
      return {
        kind: 'whisper',
        text: formatTblPrintf(tmpl, senderName, message),
        color,
        sender: senderName,
        rawMessage: message,
      }
    }
    case 0x04: {
      // 0x6fb2f7ea: S2C 0x26 chatType == 0x04 (System / global broadcast message)
      return {
        kind: 'system',
        text: message,
        color: input.color ?? 4,
        sender: senderName,
        rawMessage: message,
      }
    }
    default: {
      return {
        kind: 'system',
        text: senderName ? `${senderName}: ${message}` : message,
        color,
        sender: senderName,
        rawMessage: message,
      }
    }
  }
}

