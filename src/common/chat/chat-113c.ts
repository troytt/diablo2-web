  const startX = leftPanelOpen
    ? Math.floor(screenWidth / 2) + CHAT_OVERLAY_START_X
    : CHAT_OVERLAY_START_X
  const startY = hasTopLeftPortraits
    ? CHAT_OVERLAY_START_Y_WITH_PORTRAITS
    : CHAT_OVERLAY_START_Y_NO_PORTRAITS
