// ─── TBL Lookup & Printf Formatting ──────────────────────────────────────────

/**
 * Resolves a 1.13c global string table index (`D2Lang_10003` convention):
 * - `0 .. 9999`     -> `string#<index>` (`d2data.mpq`)
 * - `10000 .. 19999` -> `patchstring#<index - 10000>` (`Patch_D2.mpq`)
 * - `>= 20000`      -> `expstring#<index - 20000>` (`d2exp.mpq`)
 */
export function resolveChatTblIndex(globalIdx: number, lang: 'ENG' | 'CHI' = 'CHI'): string {
  let key: string
  if (globalIdx >= 20_000) {
    key = `expstring#${globalIdx - 20_000}`
  } else if (globalIdx >= 10_000) {
    key = `patchstring#${globalIdx - 10_000}`
  } else {
    key = `string#${globalIdx}`
  }
  return resolveTblKey(key, lang) ?? resolveTblKey(key, 'ENG') ?? ''
}

/**
 * Resolves unit overhead speech bubble text per `D2Client.dll`:
 * - `0x6fb2dc00` (`MSG_DrawPlayerOverhead`): Player overhead text prefixed with `0xFF, 0xFF` (`"ÿÿ<id>"`)
 *   resolves `D2Lang_GetStringByIndex(id)` (`1069..1295`, `21895..22037`, `10916`, `21894`).
 *   Otherwise player `!text` overhead chat is rendered as literal text.
 * - `0x6fb2daa0` (`MSG_DrawMonsterOrObjectOverhead`) & `D2Game.dll` `0x6fc8da80` (`OBJECTS_OperateFn_Shrine`):
 *   Monster (`unitType === 1` / `'monster'`) and Object (`unitType === 2` / `'object'`, e.g., Shrines sending
 *   `sprintf("%i", bInteractType + 3683)` = `"3683".."3705"`) store decimal `.tbl` string indices in `pHoverText`
 *   and resolve them via `atoi` + `D2Lang_GetStringByIndex(nStrId)` (`0 < nStrId < 0xFFFF`).
 */
export function resolveOverheadBubbleText113c(
  rawText: string,
  unitType?: string | number | undefined,
  lang: 'ENG' | 'CHI' = 'CHI',
): string {
  if (!rawText) return ''
  const trimmed = rawText.trim()
  if (!trimmed) return ''

  // 0x6fb2dc00: player voice-wheel / help emote ("ÿÿ<decimal>")
  if (
    trimmed.length > 2 &&
    (trimmed.charCodeAt(0) === 0xff || trimmed.charCodeAt(0) === 0xfffd) &&
    (trimmed.charCodeAt(1) === 0xff || trimmed.charCodeAt(1) === 0xfffd)
  ) {
    const idStr = trimmed.slice(2).trim()
    if (/^\d+$/.test(idStr)) {
      const strId = Number.parseInt(idStr, 10)
      if (strId > 0 && strId < 0xffff) {
        const resolved = resolveChatTblIndex(strId, lang)
        if (resolved) return resolved
      }
    }
  }

  // 0x6fb2daa0: monster (1) & object (2, e.g. Shrines) decimal .tbl string index
  const normUnit =
    typeof unitType === 'string' ? unitType.split(':')[0]!.trim().toLowerCase() : unitType
  const isPlayerUnit = normUnit === 0 || normUnit === 'player'
  if (!isPlayerUnit && /^\d+$/.test(trimmed)) {
    const strId = Number.parseInt(trimmed, 10)
    if (strId > 0 && strId < 0xffff) {
      const resolved = resolveChatTblIndex(strId, lang)
      if (resolved) return resolved
    }
  }

  return trimmed
}

/**
 * Formats a 1.13c `.tbl` printf template containing `%s` and/or `%d` placeholders.
 */
export function formatTblPrintf(template: string, ...args: Array<string | number>): string {
  let argIdx = 0
  return template.replace(/%[sd]/g, (token) => {
    if (argIdx >= args.length) return token
    const val = args[argIdx++]
    return val !== undefined ? String(val) : ''
  })
}

