function buildBaseMap(rows: readonly BaseRow[], kind: 'armor' | 'weapon' | 'misc'): Map<string, ItemBaseMeta> {
  const map = new Map<string, ItemBaseMeta>()
  for (const [code, invWidth, invHeight, minDefense, flags] of rows) {
    const meta: ItemBaseMeta = {
      code,
      kind,
      stackable: (flags & 1) !== 0,
      hasDurability: (flags & 2) !== 0,
      nodurability: (flags & 4) !== 0,
      isTome: (flags & 8) !== 0,
      isBodyPart: (flags & 16) !== 0,
      isGold: (flags & 32) !== 0,
      quest: (flags & 64) !== 0,
      questDiffCheck: (flags & 128) !== 0,
      compactSave: (flags & 256) !== 0,
      invWidth,
      invHeight,
      minDefense,
    }
    map.set(code, meta)
    const padded = code.padEnd(4, ' ').slice(0, 4)
    if (!map.has(padded)) {
      map.set(padded, meta)
    }
  }
  return map
}

